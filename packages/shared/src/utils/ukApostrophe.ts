/**
 * Last validated: 2026-08-26
 * Status: Active
 *
 * Канонічний апостроф і згортання його варіантів — канон
 * `docs/01-product/copy/style-guide.uk.md` §1.10.
 *
 * AI-CONTEXT: у показі український апостроф — рівно `ʼ` (U+02BC). Це
 * буквений знак, а не пунктуація, тож він єдиний із трьох правильний.
 * Але код читає ще й ЧУЖИЙ текст, який ми не контролюємо:
 *
 *  · підписи категорій, збережені попередніми версіями застосунку через
 *    `'` (U+0027) — вони лежать у сховищі користувача й не переписуються;
 *  · розшифровку мовлення від Whisper, яка віддає то `'`, то `’`, то `ʼ`;
 *  · пошуковий запит, який людина набирає тією клавіатурою, що має.
 *
 * Тому символ показу й символ порівняння — різні задачі. Показ канонічний,
 * а КОЖНА межа зіставлення спершу згортає всі варіанти в один
 * (`foldApostrophes`), і тоді вже порівнює. Саме відсутність цього кроку
 * зірвала першу спробу міграції 2026-08-26: заміна символу в ключах
 * мовчки розірвала зіставлення з даними, записаними раніше.
 *
 * AI-DANGER: не «оптимізуй» це, прибравши згортання там, де ключі й так
 * канонічні. Ключ канонічний — ВХІД ні, і саме вхід тут непередбачуваний.
 */

/** Канонічний апостроф показу (MODIFIER LETTER APOSTROPHE). */
export const UA_APOSTROPHE = "ʼ";

/**
 * Усі форми, що трапляються на вході: ASCII `'`, ліва й права типографські
 * лапки, канонічний `ʼ`. Ліву (`‘`) тримаємо теж — її дають деякі
 * мобільні клавіатури з автозаміною.
 */
const RX_APOSTROPHE_VARIANTS = /['‘’ʼ]/g;

/**
 * Зводить будь-яку форму апострофа до канонічної. Застосовувати на ОБОХ
 * боках порівняння — і до ключа, і до входу; згортання лише одного боку
 * не дає нічого.
 */
export function foldApostrophes(value: string): string {
  return value.replace(RX_APOSTROPHE_VARIANTS, UA_APOSTROPHE);
}
