/**
 * Канонічна нормалізація пошукового ключа продукту.
 *
 * Один рядок, за яким шукається товар і в каталозі на сервері
 * (`product_catalog.name_norm`), і в локальній базі на клієнті
 * (`FoodProduct.norm`). Тримати його в одному місці критично: якщо два
 * боки нормалізують по-різному, той самий товар знаходиться в одному
 * сховищі й не знаходиться в іншому, причому мовчки.
 *
 * AI-CONTEXT: чому це рахує застосунок, а не Postgres. `lower()` згортає
 * регістр за колацією БАЗИ, і під ctype C кирилиця лишається
 * незгорнутою (перевірено на живому Postgres 16:
 * `lower('Яготинське')` → `'Яготинське'`). Локаль продової бази задає
 * Coolify при створенні ресурсу, і покладатись на неї не можна. JS
 * `toLowerCase()` згортає Unicode правильно за будь-якої локалі, тож
 * ключ обчислюється тут і кладеться в БД готовим. Повний розбір — у
 * шапці міграції `123_product_catalog.sql`.
 */

/**
 * Звести довільний текст до пошукової форми.
 *
 * Кроки й навіщо кожен:
 *   1. `trim` + стиснення пробілів — джерела рясно віддають подвійні
 *      пробіли й переноси всередині назв;
 *   2. `toLowerCase` — регістронезалежний пошук;
 *   3. уніфікація апострофів — в українських назвах трапляються і `'`,
 *      і `’`, і `ʼ`; без зведення «мʼясо» не знайдеться за «м'ясо».
 */
export function normalizeProductText(input: unknown): string {
  // AI-DANGER: згортає в ASCII `'`, а НЕ в канонічний `ʼ` (§1.10), і це
  // свідомо. Результат не показується — він персиститься в
  // `generic_foods.name_norm` і зіставляється SQL-ом (`LIKE`, `<%`,
  // `aliases @>`). Зміна символу-цілі мовчки знецінила б кожен уже
  // записаний ключ, доки не пройде повторний сід, тобто пошук їжі
  // просто перестав би знаходити. Апострофні форми тут і так зведені
  // разом, тож для міграції показу ця функція безпечна як є.
  return String(input ?? "")
    .trim()
    .toLowerCase()
    .replace(/[’'ʼ`]/g, "'")
    .replace(/\s+/g, " ");
}

/**
 * Пошуковий ключ товару: назва разом із брендом.
 *
 * Бренд входить у ключ навмисно — людина шукає «яготинське молоко», а не
 * окремо поле `name`. Порядок «назва, потім бренд» зафіксований, щоб
 * ключі, обчислені на різних поверхнях, збігалися побайтово.
 */
export function buildProductSearchKey(name: unknown, brand?: unknown): string {
  const parts = [name, brand]
    .map((p) => String(p ?? "").trim())
    .filter((p) => p.length > 0);
  return normalizeProductText(parts.join(" "));
}
