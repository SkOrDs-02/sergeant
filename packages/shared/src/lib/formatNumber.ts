/**
 * Форматування чисел під uk-UA з ОДНИМ роздільником розрядів на весь продукт.
 *
 * # Навіщо обгортка над `toLocaleString`
 *
 * `Intl` для uk-UA групує розряди вузьким нерозривним пробілом U+202F. У
 * наших шрифтах він майже непомітний: «1 234 567» читається як суцільне
 * число — рівно та скарга, з якої почалась ця зміна (бета-тестер,
 * 2026-08-22: «а можна пробіли після кожних 3 знаків, щоб легше читалось»).
 * Тому одразу після форматування U+202F міняється на звичайний нерозривний
 * пробіл U+00A0: він видимої ширини, але так само не дає числу переноситись.
 *
 * AI-DANGER: не плутати з `NARROW_NBSP` із `formatMoney.ts`. Той теж U+202F,
 * але стоїть МІЖ сумою і символом валюти — там вузький пробіл правильний за
 * типографікою. Заміна тут стосується лише роздільника РОЗРЯДІВ.
 *
 * Викликати цей хелпер, а не `toLocaleString("uk-UA")` напряму: інакше та
 * сама сума в сусідніх поверхнях знову розійдеться на два різні пробіли.
 */
/** Роздільник розрядів. Нерозривний, щоб число не ламалось на два рядки. */
export const GROUP_SEPARATOR = "\u00A0";

/** Те, що вставляє `Intl` і що ми заміняємо. */
const INTL_GROUP_SEPARATOR = /\u202f/g;

export function formatNumberUk(
  value: number,
  options?: Intl.NumberFormatOptions,
): string {
  try {
    return value
      .toLocaleString("uk-UA", options)
      .replace(INTL_GROUP_SEPARATOR, GROUP_SEPARATOR);
  } catch {
    // Рантайми без повного Intl — віддаємо число без групування, аби не
    // впасти. Втрата косметична, а альтернатива — порожній екран.
    return String(value);
  }
}
