/**
 * - `destructive` — незворотне: видалення або перезапис даних. Виконанню
 *   передує явне підтвердження людини (канон §8).
 * - `reversible` — наслідок скасовний тим самим інструментом або через UI.
 *   Виконується одразу; страховка — тост «скасувати».
 */
export type ToolRisk = "destructive" | "reversible";

/**
 * Реєстр ризикових інструментів. Кожен запис має причину — саме причина, а
 * не «схоже на небезпечне», вирішує режим.
 *
 * AI-DANGER: не додавай сюди інструмент «про всяк випадок». Зайве
 * `destructive` навчає користувача клацати «Так» не читаючи, і тоді
 * підтвердження перестає працювати там, де воно справді потрібне.
 */
export const TOOL_RISK: Readonly<Record<string, ToolRisk>> = {
  // Видаляє ручну транзакцію з локального сховища + дзеркалить видалення в
  // SQLite. Хендлер `undo` не повертає — відновити нічим.
  delete_transaction: "destructive",

  // Видаляє факт із Memory Bank. `undo` немає; факт може повернутись лише
  // якщо користувач сам згадає його в чаті знову.
  forget: "destructive",

  // Перезаписує категорії до 50 транзакцій за патерном; попередні значення
  // не зберігаються. Це рівно «перезапис» із рішення founder-а. Помʼякшення
  // у вигляді `dry_run` за замовчуванням існує, але воно captures лише
  // випадок, коли модель САМА вирішила показати превʼю.
  batch_categorize: "destructive",

  // Стирає місячні кеші транзакцій за весь діапазон дат. Дані відновлювані
  // повторним синком з банку, але поки банк недоступний — їх просто немає.
  import_monobank_range: "destructive",

  // Стирає ВСІ позиції активної комори за один виклик. `undo` немає:
  // виконавець не зберігає знімок, а відновити перелік продуктів людина
  // може лише вручну. Пара `consume_from_pantry` (не-деструктивний) плюс
  // `clear_pantry` (деструктивний) — навмисно різні інструменти, а не
  // прапорець: гейт підтвердження іменний (`requiresConfirmation(name)`),
  // тож деструктивний РЕЖИМ звичайного інструмента пройшов би повз нього.
  clear_pantry: "destructive",

  // Додає id у список прихованих. Зворотна дія існує в UI Фініка.
  hide_transaction: "reversible",

  // Той самий інструмент приймає `archived: false` — тобто вміє себе
  // скасувати; плюс екран архіву в налаштуваннях Рутини.
  archive_habit: "reversible",

  // AI-CONTEXT (B39, 2026-08-25): `set_budget_limit`, `set_monthly_plan`,
  // `update_budget`, `change_category` перезаписують значення без
  // читання попереднього — тобто формально підпадають під «перезапис» з
  // рішення founder-а #8. Але founder уточнив межу саме тут: підтвердження
  // потребує лише НЕЗВОРОТНЕ. Ці чотири інструменти отримали робочий
  // `undo`, що читає попереднє значення ПЕРЕД записом і повертає closure,
  // яка пише його назад (той самий 5-секундний undo-тост, що й у
  // `create_transaction`) — тобто зворотні, а не деструктивні. Блокуючий
  // модал лишається тільки для дій без reverse-snapshot-у.
  set_budget_limit: "reversible",
  set_monthly_plan: "reversible",
  update_budget: "reversible",
  change_category: "reversible",
};

/** Усі ризикові інструменти — для бейджа-попередження в каталозі й картці. */
export const RISKY_TOOL_IDS: ReadonlySet<string> = new Set(
  Object.keys(TOOL_RISK),
);

/** `true` — інструмент показується з попереджувальним маркуванням. */
export function isRiskyTool(name: string): boolean {
  return RISKY_TOOL_IDS.has(name);
}

/**
 * `true` — виконанню має передувати явна згода людини.
 *
 * Це і є гейт із канону §8. Раніше функції не існувало взагалі: `isRiskyTool`
 * впливала лише на колір картки ПІСЛЯ виконання, тобто продукт повідомляв
 * post factum і компенсував це undo-тостом — модель «undo замість confirm»,
 * яку канон називає визнаним боргом.
 */
export function requiresConfirmation(name: string): boolean {
  return TOOL_RISK[name] === "destructive";
}
