/**
 * Контракт поле-рівневого злиття `nutrition_prefs.prefs_json` у sync v2
 * (аудит 2026-10-01, `data-04`, п. 5 «Мінімального фіксу»).
 *
 * WHY. Сервер замінював `prefs_json` цілком за LWW: клієнт зі застарілим або
 * холодним (дефолтним) знімком затирав шаблони страв, ціль ккал, воду й
 * нагадування, яких сам не торкався. Тепер клієнт МОЖЕ надіслати лише змінені
 * ключі й позначити op прапорцем `prefs_merge: true`: сервер накладе їх на
 * наявний `prefs_json` на рівні верхніх ключів (`existing || patch`).
 *
 * Зворотна сумісність: op без прапорця (усі наявні клієнти) працює як раніше,
 * повна заміна. Масиви (`mealTemplates`) і вкладені значення замінюються
 * цілком, а не зливаються. Ключ, якого нема в патчі, сервер не чіпає; щоб
 * скинути поле, шли явний `null`/дефолт, бо «пропуск» не видаляє ключ.
 *
 * LWW на рівні рядка лишається: патч старіший за серверний `updated_at`
 * відхиляється з `lww_conflict`, як і повний знімок.
 *
 * Журнал: у `sync_op_log` сервер кладе вже ЗЛИТИЙ повний `prefs_json` без
 * прапорця, щоб pull на інших пристроях (які цього прапорця не знають) не
 * замінив локальні prefs голим патчем.
 */
export const NUTRITION_PREFS_MERGE_FIELD = "prefs_merge" as const;

/** Форма `row` для `table: "nutrition_prefs"` у `POST /api/v2/sync/push`. */
export interface NutritionPrefsSyncRow {
  user_id: string;
  /** JSON-обʼєкт або його рядкове подання. Із `prefs_merge` це лише патч. */
  prefs_json?: string | Record<string, unknown>;
  active_pantry_id?: string | null;
  /** `true` → `prefs_json` є патчем верхніх ключів, а не повним знімком. */
  prefs_merge?: boolean;
}
