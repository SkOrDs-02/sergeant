/**
 * Провенанс метрик — версія МЕТОДИКИ підрахунку, а не версія даних.
 *
 * Навіщо. Хвиля 1 (`docs/90-work/planning/product-knowledge-backlog.md`)
 * переводить похідні числа — % виконання звичок, знаменник heatmap, витрати
 * за період, середні ккал — на канонічні агрегації. Кожен такий cutover дає
 * **одноразовий стрибок цифри**, яку користувач уже бачив:
 * [ADR-0079](../../../../docs/04-governance/adr/0079-frozen-past-and-canonical-denominator.md)
 * §3-§4 називає це неминучим і прямо вимагає версію разом зі стрибком.
 *
 * Небезпека, яку це закриває, конкретна. Коуч тримає до 12 тижнів у
 * `coach_memory` і подає 8 у промпт. Якщо методику змінити мовчки, він
 * побачить стрибок визначення й прочитає його як **зміну поведінки
 * користувача** — скаже «ти став витрачати більше» або «ти закинув звички»
 * там, де людина не змінила нічого. Тому тренд НЕ можна будувати через межу
 * версій; записи різних версій порівнювати як динаміку заборонено.
 *
 * Семантика значень:
 *
 * - поле **відсутнє** у збереженому записі → вважати `0` (легасі, до
 *   запровадження провенансу). Переписувати старі записи ми НЕ будемо —
 *   вони штампуються лише тим, що прийшло разом із ними;
 * - `1` — поточна методика (стан до cutover-ів Хвилі 1);
 * - кожен наступний cutover, що рухає видиме число, піднімає константу на 1
 *   у ТОМУ Ж патчі, що змінює методику. Підняти її окремо «про запас» —
 *   гірше, ніж не піднімати: версія перестане відповідати числам.
 *
 * AI-CONTEXT: це імʼя де-факто незворотне — воно потрапляє у збережені
 * дайджести й у `coach_memory`, тож ренейм осиротить усю накопичену історію.
 * Саме тому контракт заморожується ДО першого cutover-у, а не разом із ним.
 */

/**
 * Поточна версія методики підрахунку похідних метрик.
 *
 * Історія (кожен пункт — cutover, що зрушив видиме число):
 *
 * - `1` — стан до Хвилі 1;
 * - `2` — heatmap звичок перейшов на знаменник за розкладом + заморозку
 *   минулого (`W1-HEATMAP-DENOM` стадія 3, ADR-0079 §3);
 * - `3` — тижневий дайджест і Hub-Reports перейшли на канонічні агрегації
 *   (`W1-CANON-AGG` стадія 4): % виконання звичок рахується за розкладом
 *   (звичка «Пн/Ср/Пт» 3/3 — це 100%, а не 43%), середні ккал у Hub-Reports
 *   діляться на дні з ≥1 прийомом, а не на дні з наявним ключем у лозі.
 * - `4` — витрати за період включають ГОТІВКУ (`W1-CANON-AGG` стадія 2d):
 *   тижневий дайджест, коуч-інсайт і картка Витрат у Звітах читають
 *   канонічний всесвіт `bank + manual` замість банк-only. Це єдиний
 *   cutover Хвилі 1, що піднімає число ВГОРУ: у кого є ручні витрати,
 *   тижневий підсумок зросте рівно на їхню суму. Тренд через межу 3→4
 *   читати не можна — зростання тут означає «стало видно більше», а не
 *   «людина стала витрачати більше».
 * - `5` — пауза перестала бути ретроактивною в rate-конвеєрах
 *   (`W1-HEATMAP-DENOM`, ADR-0079 §2): модуль Звички, тижневий дайджест і
 *   Hub-Reports рахують знаменник із `pausedFrom = сьогодні`, тож поставлена
 *   сьогодні пауза більше не переписує минулі періоди. Heatmap так рахував
 *   уже з версії 2 — ця версія доводить rate до тієї ж семантики.
 * - `6` — стрік звичок став ГНУЧКИМ (Хвиля 4, канон `routine.md` §4/§5).
 *   Три зміни рухають число, і всі три — вгору:
 *   (а) сьогоднішній незакритий день більше не читається як обрив, тож
 *   щоранку до першої відмітки стрік показував 0, а тепер показує вчорашню
 *   довжину; (б) заявлена датована пауза (`Habit.pauseIntervals`) випадає
 *   з розкладу, а не рахується серією пропусків; (в) мовчазний пропуск
 *   прощається grace-бюджетом (1 заморозка за кожні 7 виконаних днів,
 *   стеля 4, два підряд не прощаються ніколи). Заразом «не зміг з
 *   причиною» (`RoutineState.skips`) виходить зі ЗНАМЕННИКА rate-конвеєрів
 *   — такий день не провал і не виконання. Тренд через межу 5→6 читати не
 *   можна: зростання означає «стрік перестав ламатись об речі, які канон
 *   ніколи не вважав провалом», а не «людина стала робити більше».
 * - `7` — стрік Фізрука став ТИЖНЕВИМ (Хвиля 4, канон `fizruk.md` §7).
 *   Щоденна логіка `computeStreakDays` карала за правильний день
 *   відпочинку: день без тренування розривав серію (крім однієї доби
 *   grace), а дата була локальною, не київською, тож поза Києвом серія
 *   рвалась на off-by-one. Тепер веб показує «N тижнів поспіль із ≥2
 *   тренувань» із київськими межами тижня. Число рухається в ОБИДВА боки:
 *   у того, хто тренується щодня, «14 днів» стане «2 тижнями», а в того,
 *   хто тренується двічі на тиждень із відпочинком, серія вперше перестане
 *   бути нулем. Тренд через межу 6→7 читати не можна — це різні одиниці.
 *   `streakDays` лишається в payload-і для мобілки (поза скоупом), але веб
 *   його не показує.
 * - `8` — 1RM СТАРІЄ, і калькулятор навантаження рахує від зниженого
 *   орієнтира (Хвиля 4, канон `fizruk.md` §6). Раніше `best1rm` був
 *   максимумом за всю історію без поля віку, тож після місяця перерви
 *   продукт пропонував робочу вагу від піка, якого людина вже не підніме.
 *   Тепер після 28 днів без вправи 1RM позначається застарілою, а орієнтир
 *   знижується на 2.5% за кожен тиждень понад поріг (підлога 75%); зняття
 *   позначки травми вмикає той самий мʼякий режим на 21 день із
 *   коефіцієнтом 0.9. Число рухається ВНИЗ і тільки вниз — і саме в цьому
 *   сенс: воно й мало бути нижчим. Тренд через межу 7→8 читати не можна —
 *   зниження означає «орієнтир став чесним», а не «людина ослабла». Сам
 *   рекорд не переписаний: `best1rm` лишається тим самим числом.
 * - `9` — запис самопочуття ПРОТУХАЄ (Хвиля 4, аудит fizruk E-3).
 *   `computeWellbeingMultiplier` брав останній запис зі сном без вікна
 *   давності, тож єдине «8.5 год сну» місячної давності НАЗАВЖДИ прискорювало
 *   видиме відновлення (множник до 0.7) — тобто зсувало кольори recovery в
 *   бік «тренуй раніше» саме там, де на них тримається травма-safety.
 *   Тепер запис старший за 72 год у розрахунку не бере участі, і множник
 *   відкочується до 1.0. Число рухається в ОБИДВА боки: у того, хто записав
 *   хороший сон і покинув журнал, втома зросте (кольори стануть
 *   консервативнішими); у того, хто записав поганий сон і покинув, — впаде.
 *   Тренд через межу 8→9 читати не можна: зміна означає «старий запис
 *   перестав вдавати сьогоднішній стан», а не зміну самопочуття.
 * - `10` — тижневий дайджест і коуч-інсайт нарешті ЧИТАЮТЬ персональні
 *   налаштування Фініка (bug-репорт 2026-08-09). Обидва брали оверрайди
 *   категорій і excluded-set із шести LS-ключів, tombstone-нутих ще Stage 8
 *   PR #057k / Stage 13 PR #075: писати в них перестали, а residual-import
 *   дренає їх на буті — тож на реальному пристрої набір приїжджав порожнім.
 *   Наслідок, який бачив користувач: переказ між ВЛАСНИМИ картками, давно
 *   позначений внутрішнім, рахувався витратою (і доходом на вхідній нозі), а
 *   в «куди пішли гроші» стояв сирий `MCC 4829`. Тепер джерело — канонічний
 *   SQLite-кеш (LS лишився fallback-ом на холодний перший кадр), excluded-set
 *   бачить і мітку переказу на самій транзакції (`categoryId`/`type`), а
 *   підписи резолвить канонічна `getCategory` — та сама, що у стрічці
 *   транзакцій, тож невідомий MCC стає «Інше». Число рухається ВНИЗ і тільки
 *   вниз: у кого є позначені перекази або приховані транзакції, тижневі
 *   витрати впадуть рівно на їхню суму. Тренд через межу 9→10 читати не
 *   можна — падіння означає «перестали рахувати те, що ніколи не було
 *   витратою», а не «людина стала витрачати менше».
 * - `11` — разові звички (`recurrence: "once"`) вийшли з УСІХ агрегатних
 *   метрик модуля Звички (канон `routine.md` §7 п.2, рішення founder-а
 *   2026-08-30): стрік (жорсткий і гнучкий), heatmap (обидва режими
 *   знаменника), % виконання за період і per-habit зрізи. `once` — «легкий
 *   виняток, не задача»: разову подію видно в чек-листі дня і можна
 *   відмітити, але жодного накопичувального числа вона не рухає. Число
 *   рухається в ОБИДВА боки: невідмічена разова подія перестає тягнути
 *   відсоток униз, відмічена — перестає підпирати його вгору, а стрік, що
 *   тримався на самотній `once`-відмітці, стане нулем. Тренд через межу
 *   10→11 читати не можна — зміна означає «разові події перестали вдавати
 *   звички», а не зміну поведінки людини.
 * - `12` — звичка «N разів на тиждень» (`recurrence: "flexible"`, спека
 *   `routine-flexible-weekly-frequency.md`, рішення founder-а 2026-08-26)
 *   перестала вважатись запланованою в дні, коли тижневу ціль уже добрано.
 *   Раніше такого режиму не існувало взагалі, тож на самих гнучких звичках
 *   порівнювати нема чого — але межа потрібна через ДВА наслідки для тих,
 *   хто їх заведе. Перший: у heatmap-режимі `"scheduled"` гнучка звичка
 *   сиділа б у знаменнику ЩОДНЯ, і людина з ціллю «3 рази» бачила б чотири
 *   незафарбовані дні щотижня — сітка читалась би як «пропустив», хоча вона
 *   зробила рівно те, що планувала. Тепер такі дні в знаменник не входять,
 *   і відсоток дня росте. Другий: стрік і `% виконання` для цих звичок
 *   рахуються ТИЖНЯМИ (`weeklyGoalStreakBreakdown`), а не днями — одиниця
 *   числа інша, тож підписи в UI теж змінені. Число рухається ВГОРУ для
 *   всіх, хто має хоч одну гнучку звичку, і не рухається ні на йоту для
 *   решти. Тренд через межу 11→12 на таких акаунтах читати не можна —
 *   зміна означає «перестали карати за дні, у які нічого й не планувалось».
 */
export const METRICS_VERSION = 12;

/**
 * Версія, яку слід приписати запису без явного поля.
 *
 * Записи, створені до запровадження провенансу, версії не несуть. Вони НЕ
 * еквівалентні `METRICS_VERSION`: методика на момент їх створення невідома,
 * тож єдине чесне трактування — окрема «нульова» версія.
 */
export const LEGACY_METRICS_VERSION = 0;

/** Нормалізувати можливо-відсутнє поле версії у число. */
export function resolveMetricsVersion(value: unknown): number {
  return typeof value === "number" && Number.isInteger(value) && value >= 0
    ? value
    : LEGACY_METRICS_VERSION;
}

/**
 * Чи можна порівнювати два записи як ТРЕНД.
 *
 * Повертає `false` для різних версій — саме цю перевірку має робити кожен
 * споживач, що будує динаміку (коуч, тижневий графік, «порівняй тижні»).
 */
export function comparableAsTrend(a: unknown, b: unknown): boolean {
  return resolveMetricsVersion(a) === resolveMetricsVersion(b);
}
