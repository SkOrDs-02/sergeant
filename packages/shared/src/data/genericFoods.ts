/**
 * Канонічний корпус базової їжі без штрихкоду.
 *
 * ЄДИНЕ джерело правди для двох споживачів:
 *   * сервер — засіває `generic_foods` (міграція 124) і шукає по ній;
 *   * клієнт — засіває локальну IndexedDB для офлайну.
 *
 * Тримати його тут, а не в `apps/web`, обовʼязково: дві копії розійшлись
 * би першою ж правкою, і той самий продукт мав би різні числа онлайн і
 * офлайн — розбіжність, яку користувач побачив би як «застосунок бреше».
 *
 * ЩО ЦЕ ЗАКРИВАЄ. На реальній полиці третина позицій має
 * внутрішньомагазинні вагові коди (вимір 2026-08-22: 35 зі 104) — огірок,
 * кабачок, сир на вагу. Такий код генерує касовий термінал конкретної
 * мережі, тож у глобальних базах штрихкодів його немає й ніколи не буде.
 * Єдиний шлях — знайти базову їжу НАЗВОЮ, і саме для цього цей корпус.
 *
 * ЯК ПРАВИТИ. Числа — на 100 г їстівної частини. Перед комітом сюди
 * дивиться `genericFoods.test.ts`: він звіряє калорійність із макросами
 * за Атвотером (4/9/4 + 7 на спирт) і ловить друкарську помилку в цифрі
 * раніше, ніж вона доїде до чийогось денного плану.
 *
 * `slug` — стабільний ідентифікатор, який лягає в `nutrition_meals.food_id`.
 * НЕ ПЕРЕЙМЕНОВУВАТИ вже наявні: це осиротить історію прийомів їжі.
 * Українську назву міняти можна вільно, slug — ні.
 */

export interface GenericFoodMacros {
  kcal: number;
  protein_g: number;
  fat_g: number;
  carbs_g: number;
}

export interface GenericFood {
  /** Стабільний латинський ключ. Не перейменовувати — див. шапку файлу. */
  slug: string;
  /** Українська назва для показу. */
  name: string;
  /** Категорія для групування у видачі. */
  category: string;
  /** На 100 г їстівної частини. */
  per100: GenericFoodMacros;
  /**
   * Синоніми, за якими людина реально шукає: «помідор» проти «томат».
   * Куровані, не для всіх позицій — лише де запит розходиться з каноном.
   */
  aliases?: readonly string[];
  /** Спирт, г/100 г. Потрібен воротам Атвотера: етанол дає ~7 ккал/г. */
  alcohol_g?: number;
  /** Типова порція. Дефолт 100 г для всього вагового. */
  defaultGrams?: number;
}

