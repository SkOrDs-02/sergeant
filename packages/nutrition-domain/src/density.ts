/**
 * Щільність харчових рідин — єдина таблиця на весь модуль Харчування.
 *
 * Status: Active
 *
 * Живе окремим файлом, а не всередині `pantryConsume.ts`, суто через
 * порядок імпортів: `units.ts` потребує щільності, щоб звести масу рідини
 * до об'єму, а `pantryConsume.ts` уже залежить від `pantrySources.ts`, який
 * залежить від `units.ts`. Спільна таблиця нижче за всіма трьома розриває
 * цикл.
 *
 * AI-CONTEXT: таблиця навмисно груба і НЕПОВНА — це не довідник. Її межа
 * і є продуктовим рішенням: {@link knownDensityGPerMl} повертає `null` для
 * всього, чого тут немає, і викликач тоді НЕ конвертує взагалі. Дефолт
 * 1.0 (`DEFAULT_DENSITY_G_PER_ML`) лишається тільки для списання, де
 * альтернатива — не списати нічого; для злиття позицій він означав би
 * тихе «900 г = 900 мл», а це для меду помилка на 30%.
 */
import { canonicalFoodKey } from "./pantryTextParser.js";

/** Густина за замовчуванням (вода-подібна), коли продукту немає в таблиці. г/мл. */
export const DEFAULT_DENSITY_G_PER_ML = 1.0;

/**
 * Груба таблиця густин (г/мл). Ключ — `canonicalFoodKey(name)`, тож
 * відмінкові й множинні форми («молока», «олії») зводяться до канонічної
 * форми перед пошуком.
 */
export const DENSITY_G_PER_ML: Readonly<Record<string, number>> = {
  молоко: 1.03,
  кефір: 1.03,
  ряжанка: 1.03,
  йогурт: 1.03,
  вершки: 1.01,
  олія: 0.92,
  "оливкова олія": 0.92,
  мед: 1.42,
};

/**
 * Щільність продукту, або `null` коли вона НЕ відома.
 *
 * Саме на цьому `null` тримається межа з § Рішення 7 канону: масу зводимо
 * до об'єму лише там, де знаємо коефіцієнт. Для решти «Молоко 900 г» і
 * «Молоко 1 л» лишаються двома позиціями — дві чесні позиції кращі за одну
 * з вигаданим числом.
 */
export function knownDensityGPerMl(name: unknown): number | null {
  return DENSITY_G_PER_ML[canonicalFoodKey(name)] ?? null;
}

/** Густина (г/мл) для продукту; default {@link DEFAULT_DENSITY_G_PER_ML}. */
export function densityFor(name: unknown): number {
  return knownDensityGPerMl(name) ?? DEFAULT_DENSITY_G_PER_ML;
}
