// Сигнали про темп витрат: три рекомендації, які раніше жили кожна сама по
// собі й сходились на екрані суперечливо (рішення власника 2026-10-01,
// «Одна правда про витрати»).
//
//   • `finyk_daily_vs_weekly_pace`  – сьогодні вище середнього (денна);
//   • `spending_velocity_high`      – тиждень вище минулого (попередження);
//   • `spending_velocity_low`       – тиждень нижче минулого (похвала).
//
// Правила, що з них випливають:
//   1. Одна картка про темп за раз: коли спрацювала денна, тижнева (обидві її
//      гілки) мовчить (f2) – див. `spendingVelocityRule`.
//   2. Поки висить ПОПЕРЕДЖЕННЯ про темп, Фінік не йде в «Закрито сьогодні»
//      (f5) – споживач читає `SPENDING_PACE_WARNING_REC_IDS`.
//
// Id живуть тут, а не рядками в споживачах: клієнтський фільтр «Закрито
// сьогодні» інакше мовчки відстав би від перейменування правила.

/** Денна картка: «Сьогодні X ₴, на N% вище середнього». */
export const DAILY_PACE_REC_ID = "finyk_daily_vs_weekly_pace";

/** Тижнева картка-попередження: «Витрати на N% вище ніж минулого тижня». */
export const WEEKLY_PACE_HIGH_REC_ID = "spending_velocity_high";

/** Тижнева картка-похвала: «Витрати на N% нижче ніж минулого тижня». */
export const WEEKLY_PACE_LOW_REC_ID = "spending_velocity_low";

/**
 * Рекомендації-ПОПЕРЕДЖЕННЯ про темп витрат. Похвала (`…_low`) сюди не входить:
 * «Чудовий темп» не суперечить твердженню «записано» в купі «Закрито сьогодні».
 */
export const SPENDING_PACE_WARNING_REC_IDS: readonly string[] = [
  DAILY_PACE_REC_ID,
  WEEKLY_PACE_HIGH_REC_ID,
];
