/**
 * Барʼєр перед `page.reload()` в E2E: дочекатися, поки сервіс-воркер не
 * просто стане `activated`, а ЗАБЕРЕ КОНТРОЛЬ над сторінкою.
 *
 * AI-DANGER: без якогось барʼєра рестарт сторінки — це гонка, а не крок
 * сценарію, і саме вона тричі ламала `pantry-storage-places`
 * (`d185347` → `abd0435` → `3a69108`, щоразу підкручуванням таймінгу).
 *
 * Механіка. `precacheAndRoute` кладе весь прекеш (на 2026-09-14 — 412
 * записів, 6.7 МБ; число росте разом із продуктом)
 * у `event.waitUntil` події `install`, тож воркер не може стати
 * `activated`, поки прекеш не завершився. Заміри на цьому репо: install
 * добігає приблизно на 3.7 с після завантаження сторінки, а тест
 * доходить до рестарту приблизно на 4-5 с. Тобто `reload` стріляє
 * близько до межі переходу:
 *
 *   • воркер ще `installing` — навігація йде повз нього, у мережу;
 *   • воркер уже контролює сторінку — навігація йде через `NavigationRoute`;
 *   • перехід стається ПОСЕРЕД навігації — вона абортиться
 *     (`net::ERR_ABORTED; maybe frame was detached?`).
 *
 * **Чому умову підсилено 2026-09-11 — і чого цим НЕ доведено.**
 * `Mobile UI audit` упав у CI саме цим `ERR_ABORTED`, уже маючи барʼєр
 * перед рестартом. Перша версія чекала на `active.state === "activated"
 * && !installing`, і напрошувалось пояснення: `activated` настає ДО
 * того, як `self.clients.claim()` у `waitUntil` обробника `activate`
 * добігає (`sw.ts` кличе його після `listStaleCaches()`), тож барʼєр
 * нібито пропускав рестарт у цю щілину.
 *
 * **Замір це пояснення не підтвердив.** Пряме опитування обох умов з
 * кроком 5 мс дало `controller` на 3721 мс і стару умову на 3728 мс —
 * тобто контроль приходить РАНІШЕ, а різниця в 7 мс лежить у похибці
 * самого опитування. Спроба відтворити падіння локально теж не вдалась:
 * шість прогонів, зокрема три ЗОВСІМ без барʼєра під 8× CPU-throttling,
 * усі зелені.
 *
 * Тому умова тут підсилена не як «знайдена причина», а як precondition,
 * що збігається з тим, від чого рестарт справді залежить: навігація йде
 * через воркер лише коли той КОНТРОЛЮЄ сторінку
 * (`navigator.serviceWorker.controller`), а воркер у стані `waiting`
 * забере контроль саме на наступній навігації — тобто на нашому
 * рестарті. Обидва стани коштують нічого і на заміряному таймінгу вже
 * виконані. **Причина CI-падіння лишається невстановленою**; якщо воно
 * повториться, дивись на значення, яке повертає ця функція, — тепер
 * `timeout` відрізняється від `no-service-worker`, і виклик у
 * `pantry-storage-places.spec.ts` на нього спирається.
 *
 * **Повторилось 2026-09-14 (PR #1170, job 103830465106) — і це той самий
 * `ERR_ABORTED`. Замір, якого абзац вище просив, зроблено: барʼєр
 * ВІДПРАЦЮВАВ.** `expect(...).not.toBe("timeout")` на рядку 158 спеки
 * пройшов, падіння сталося на `page.reload` двома рядками нижче. Тобто на
 * момент перевірки воркер КОНТРОЛЮВАВ сторінку, а рестарт усе одно
 * абортився.
 *
 * Що це вилучає: «барʼєр не дочекався переходу install → activate» більше
 * не є кандидатом — саме його ця функція й міряє, і вона сказала
 * `controlling`. Лишається щось, що стається МІЖ поверненням цієї функції
 * та початком навігації, а не до неї.
 *
 * Чого це НЕ доводить: наступного кандидата тут немає. Перевірено, що
 * падіння не супроводжується нічим особливим у логі джоби — бекенд у цій
 * смузі не піднімають узагалі (`ECONNREFUSED 127.0.0.1:3000` рівно так
 * само стоїть під усіма 27 зеленими тестами), тож ані `/api/v1/me`, ані
 * `silpo/sync-state` до справи не стосуються.
 *
 * **Контрольний замір того ж дня, і він вартий окремого рядка.** Та сама
 * джоба на PR #1171 (job 103832489392) — ЗЕЛЕНА, хоча саме той PR змінює
 * код Їжі (`WeekKcalCard`, `NutritionStartPage`), а червоний #1170 Їжі не
 * торкається взагалі. Тобто залежності від вмісту диффу тут немає й у
 * зворотний бік: падає не той, хто ближче до комори.
 *
 * **Не підкручуй тут таймінг «на спробу».** Три такі правки вже було
 * (`d185347` → `abd0435` → `3a69108`), і кожна виглядала як фікс рівно до
 * наступного червоного CI.
 *
 * ── ВІДТВОРЕННЯ ЛОКАЛЬНО (2026-09-14) ──────────────────────────────────
 *
 * **Твердження «локально не відтворюється» БІЛЬШЕ НЕ ЧИННЕ.** Запис вище
 * спирався на шість зелених прогонів; цього дня тест упав на ПЕРШІЙ спробі
 * з коробки. Рецепт:
 *
 *     cd apps/web && CI=1 \
 *       PW_CHROMIUM_PATH=/opt/pw-browsers/chromium-1194/chrome-linux/chrome \
 *       pnpm exec playwright test -c playwright.mobile.config.ts \
 *         tests/mobile/pantry-storage-places.spec.ts
 *
 * `PW_CHROMIUM_PATH` тут не косметика: без нього Playwright шукає СВОЮ
 * ревізію (1228) і падає «Executable doesn't exist» ще до першого тесту.
 * Дуже ймовірно, що саме на цьому глухли попередні спроби відтворення —
 * помилка виглядає як проблема середовища, а не як провалений тест.
 * Бекенд для цієї смуги не потрібен (у CI його теж немає), конфіг сам
 * робить білд і `vite preview`.
 *
 * **Частота: приблизно половина.** Локально 1 падіння з 2 прогонів, у CI
 * того ж дня 2 з 4 (#1170 і #1172 червоні, #1171 зелений, перезапуск
 * #1170 зелений). Детермінізму немає — але ~50% цілком досить, щоб
 * налагоджувати ітераціями замість полювання наосліп.
 *
 * ── ЩО ПОКАЗАВ ТРЕЙС УПАЛОГО ЛОКАЛЬНОГО ПРОГОНУ ───────────────────────
 *
 * 1. **Локальний симптом ІНШИЙ:** `TimeoutError: page.reload: Timeout
 *    30000ms exceeded`, а не `ERR_ABORTED`. Той самий рядок, дві форми —
 *    обидві вже бачені (зависання ловили на #1037).
 * 2. **Барʼєр повернувся за 8 мс** (28921 → 28929 у трейсі), тобто воркер
 *    контролював сторінку ВІДРАЗУ, ще до першої ітерації опитування.
 * 3. **Фрейм не змінився.** `frame@32` і до рестарту, і на снапшоті після
 *    30-секундного таймауту, зі старим DOM.
 * 4. **Мережевого запиту за документом у трейсі НЕМАЄ ЖОДНОГО.**
 * 5. **Застосунок при цьому живий:** через 23 с після рестарту сторінка
 *    сходила по `/api/auth/get-session` (єдиний мережевий запис після
 *    рестарту).
 *
 * **Висновок, який це змінює.** Модель «перехід стається ПОСЕРЕД
 * навігації, і вона абортиться» (третій буліт вище) для цього прогону НЕ
 * підтвердилась: навігація не перервалась — вона **не почалась**. Запит за
 * документом зник між `page.reload()` і мережею.
 *
 * **Що стоїть саме в цьому проміжку:** `NavigationRoute` сервіс-воркера
 * (`src/sw/cache.ts`) — `NetworkFirst` з `networkTimeoutSeconds: 3` і
 * власним плагіном `userPartitionPlugin` у ланцюжку. Це НЕ обвинувачення:
 * плагін чіпає лише ключ кешу і на вигляд не зависає. Це констатація, що
 * інших кандидатів у цьому проміжку немає, і саме туди має піти наступний
 * замір — інструментувати обробник (лог на вхід/вихід `handle()`), а не
 * гадати про таймінг.
 *
 * Якщо воркера немає взагалі (його вимкнули або сторінка поза scope),
 * функція мовчки виходить: барʼєр не має ставати новою причиною падінь.
 */
export type ServiceWorkerBarrierResult =
  "controlling" | "no-service-worker" | "timeout";

export async function waitForServiceWorkerActivated(
  page: Page,
  timeout = 30_000,
): Promise<ServiceWorkerBarrierResult> {
  return page.evaluate(async (limit) => {
    if (!("serviceWorker" in navigator)) return "no-service-worker" as const;
    const deadline = Date.now() + limit;
    let sawRegistration = false;
    for (;;) {
      const reg = await navigator.serviceWorker.getRegistration();
      if (reg) sawRegistration = true;
      // Контроль, а не стан: `activated` настає ДО того, як
      // `clients.claim()` у `waitUntil` добігає (див. докстрінг).
      if (
        reg?.active?.state === "activated" &&
        !reg.installing &&
        !reg.waiting &&
        navigator.serviceWorker.controller
      ) {
        return "controlling" as const;
      }
      if (Date.now() > deadline) {
        return sawRegistration
          ? ("timeout" as const)
          : ("no-service-worker" as const);
      }
      await new Promise((r) => setTimeout(r, 50));
    }
  }, timeout);
}
