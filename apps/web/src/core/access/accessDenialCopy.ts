/**
 * Last validated: 2026-09-11
 * Status: Active
 *
 * Тексти причин недоступності, по одному на ПРИЧИНУ, а не на модуль.
 *
 * AI-CONTEXT: до цього один і той самий 401 мав у продукті пʼять різних
 * текстів — «Увійди в акаунт, щоб продовжити» (`friendlyApiError`),
 * «Доступ заборонено. Увійди ще раз» (`mapApiErrorToUserCopy`), «Ця
 * функція працює тільки з обліковим записом…» (`nutritionErrors`),
 * «Асистент працює після входу…» (`hubChatUtils`), «Сесія завершилась…»
 * (`useGroqVoiceInput`). Причина розсипання структурна: усі три мапери
 * помилок віддавали `string`, тож текст доводилось вигадувати на місці.
 *
 * Тут текст прикріплений до причини з `AccessDenial`, і тому не може
 * розійтись між поверхнями: нова поверхня не пише свій текст, вона
 * називає причину.
 *
 * Каталог `shared/i18n/uk.ts` уперся в `max-lines: 600` (Hard Rule #18),
 * тож копія тимчасово живе тут — той самий компроміс, під яким уже
 * стоїть `ChatAuthGate`. Переїзд — разом із декомпозицією каталогу.
 */
import type { AccessDenial } from "@shared/lib/api/accessDenial";

export interface AccessDenialCopy {
  title: string;
  body: string;
  /** Підпис кнопки. `null` — дії немає, лишається саме пояснення. */
  actionLabel: string | null;
  /**
   * Один рядок для місць, де картки немає — тост, інлайн-помилка.
   * Не окремий текст, а та сама причина в іншій довжині: щоб «сесія
   * завершилась» і «увійди в акаунт» не розʼїхались знову, як це вже
   * сталось із пʼятьма текстами на один 401.
   */
  short: string;
}

export function accessDenialCopy(denial: AccessDenial): AccessDenialCopy {
  switch (denial.reason) {
    case "sign-in-required":
      return {
        title: "Ця дія працює після входу",
        body: "Вона рахує на твоїх даних, тому без акаунта рахувати немає на чому. Вхід займе хвилину, і все, що вже записано на цьому пристрої, лишиться на місці.",
        actionLabel: "Увійти в акаунт",
        short: "Ця дія працює після входу в акаунт.",
      };
    case "plan-required":
      return {
        title: "Ця дія входить у Pro",
        body: "На безкоштовному тарифі вона недоступна. Подивись, що ще дає Pro, і вирішуй без поспіху.",
        actionLabel: "Подивитись тарифи",
        short: "Ця дія входить у Pro.",
      };
    case "quota-exhausted":
      return denial.preset
        ? {
            // AI-NOTE: у пресета профілю є власний безкоштовний вихід, і
            // це інша дія, ніж «спробуй завтра». Зливати ці два тексти
            // означало б відправити людину чекати там, де чекати не треба.
            title: "Автозаповнення на сьогодні вичерпано",
            body: "Ліміт оновиться завтра. Ці ж поля можна заповнити вручну в Профілі просто зараз, це безкоштовно.",
            actionLabel: "Відкрити Профіль",
            short:
              "Автозаповнення на сьогодні вичерпано, поля можна заповнити вручну в Профілі.",
          }
        : {
            title: "Ліміт на сьогодні вичерпано",
            body: "Він оновиться завтра. Усе, що вже згенеровано, лишається на місці.",
            actionLabel: null,
            short: "Ліміт на сьогодні вичерпано, він оновиться завтра.",
          };
    case "wrong-account":
      return {
        title: "Цей акаунт не має доступу",
        body: "Схоже, дія належить іншому акаунту. Перевір, під ким ти зайшов, і спробуй ще раз.",
        actionLabel: "Увійти в інший акаунт",
        short: "Цей акаунт не має доступу до дії.",
      };
    case "provider-down":
      return {
        title: "Сервіс тимчасово не відповідає",
        body: "Це не в тебе, це на нашому боці. Спробуй за кілька хвилин, дані нікуди не зникнуть.",
        actionLabel: null,
        short: "Сервіс тимчасово не відповідає, спробуй за кілька хвилин.",
      };
    case "offline":
      return {
        title: "Ця дія потребує інтернету",
        body: "Записи на пристрої працюють і без мережі, а от рахувати це доведеться онлайн. Підключись і повернись.",
        actionLabel: null,
        short: "Ця дія потребує інтернету.",
      };
  }
}
