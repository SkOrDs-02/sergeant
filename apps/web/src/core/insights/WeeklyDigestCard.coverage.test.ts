import { describe, it, expect } from "vitest";

import { coverageBadge } from "./WeeklyDigestModuleBlock";

/**
 * Coverage у тижневому дайджесті — аудит nutrition § E-4.
 *
 * Середні свідомо рахуються лише за днями із записами (канон nutrition §5.2),
 * але без знаменника поруч «середнє 1950, 95% цілі» за ДВА залоговані дні
 * читається як вдалий тиждень. Бейдж — детермінований факт біля назви модуля,
 * навмисно повз AI-текст: `summary` пише модель, і саме вона й описувала два
 * дні як успіх.
 */
describe("coverageBadge", () => {
  it("для закритого тижня показує знаменник", () => {
    expect(coverageBadge({ logged: 2, total: 7 }, false)).toBe(
      "· залоговано 2/7",
    );
  });

  it("для поточного тижня знаменник НЕ показує", () => {
    // «2/7» у середу читалось би як провал там, де минуло лише три дні —
    // фікс проти хибного сигналу сам породив би хибний сигнал.
    expect(coverageBadge({ logged: 2, total: 7 }, true)).toBe(
      "· залоговано днів: 2",
    );
  });

  it("без даних бейджа немає", () => {
    expect(coverageBadge(null, false)).toBeUndefined();
    expect(coverageBadge(undefined, false)).toBeUndefined();
  });

  it("нульовий знаменник не дає «0/0»", () => {
    // Захист від ділення періоду, якого не існує: показати «залоговано 0/0»
    // гірше, ніж не показати нічого.
    expect(coverageBadge({ logged: 0, total: 0 }, false)).toBeUndefined();
  });

  it("повний тиждень теж показує знаменник", () => {
    // Бейдж не зникає на 7/7: він має читатись як факт, а не як докір,
    // інакше його поява сама стає негативним сигналом.
    expect(coverageBadge({ logged: 7, total: 7 }, false)).toBe(
      "· залоговано 7/7",
    );
  });
});
