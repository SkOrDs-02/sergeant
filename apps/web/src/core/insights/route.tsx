import { Navigate, useLocation } from "react-router-dom";

/**
 * `/insights/*` — REDIRECT-only entry, більше НЕ самостійна оболонка.
 *
 * До цього фіксу файл рендерив власний `<main>` + `HubReports` — рівно та
 * сама пастка, яку L-1 (2026-08-08) уже закрив для `/settings`, тільки
 * тут вона прожила довше. Симптоми, з якими прийшов власник: тап по
 * картці «Звʼязки й тижневий розбір» у Можливостях відкривав екран
 * **без нижньої навігації і без скролу**. Обидва — з одного кореня:
 *
 *   1. `HubBottomNav` монтується лише з `HubHomeView`, тож на власному
 *      топ-рівневому маршруті навігації не існує в принципі. `pb-28`
 *      (112px) резервував місце під неї — глухий кут, з якого вийти
 *      можна лише жестом «назад».
 *   2. `#root` — `100dvh; overflow:hidden` (`base.css`), тож скролу
 *      документа немає взагалі: повноекранний маршрут мусить володіти
 *      власним скрол-контейнером, а цей `<main>` його не мав — вміст
 *      просто обрізався на висоті вікна. Та сама граблі задокументована
 *      в `capabilities/CapabilitiesPage.tsx`, яка свій контейнер має.
 *
 * Лікуємо НЕ додаванням третьої копії хроми, а зняттям дубля: `HubReports`
 * уже рендериться як вкладка «Звіти» хаба (`HubMainContent`, `?tab=reports`
 * → `useHubUIState.readViewFromSearch`) — з навбаром, скролом і
 * `role="tabpanel"`. Рішення власника (варіант «б»): Звіти живуть РІВНО в
 * одному місці, а `/insights` лишається лише deep-link-адресою.
 *
 * Переносимо всі query-параметри (додаючи `tab=reports`) і хеш без
 * винятків — той самий контракт, що й у `settings/route.tsx`: маршрут не
 * знає, який саме параметр комусь потрібен на тому боці, тож губити їх
 * тут не має права.
 *
 * `replace` — ОБОВʼЯЗКОВО: без нього «Назад» після редиректу веде на
 * `/insights`, який редиректить знову, і кнопка перестає працювати.
 *
 * `path: "insights/*"` (`router.tsx`) означає, що `/insights/будь-що` теж
 * матчить цей компонент; splat-хвіст ІГНОРУЄТЬСЯ — реальних під-шляхів
 * під префіксом немає (жоден `Link`/`navigate` у репо на них не веде).
 */
export function Component() {
  const location = useLocation();
  const params = new URLSearchParams(location.search);
  params.set("tab", "reports");
  const search = params.toString();

  return (
    <Navigate
      to={{
        pathname: "/",
        search: search ? `?${search}` : "",
        hash: location.hash,
      }}
      replace
    />
  );
}
