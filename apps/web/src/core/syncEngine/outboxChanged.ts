export const SYNC_OUTBOX_CHANGED_EVENT = "sergeant:sync-outbox-changed";

/**
 * Повідомляє інтерфейс, що лічильники черги застаріли. Best-effort:
 * помилку слухача ковтаємо, бо це індикатор, а не сам запис.
 */
export function emitSyncOutboxChanged(): void {
  if (typeof window === "undefined") return;
  try {
    window.dispatchEvent(new Event(SYNC_OUTBOX_CHANGED_EVENT));
  } catch {
    /* індикатор не має права зламати локальний запис */
  }
}
