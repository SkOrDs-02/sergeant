/**
 * Текст результату чат-інструмента, придатний для показу людині.
 *
 * AI-CONTEXT (перевірка першої хвилі на зібраному застосунку, 2026-11-18):
 * результат виконавця пишеться для МОДЕЛІ, і технічний id у ньому навмисний
 * (`… записано (id:m_…)`): з нього модель потім викликає `delete_transaction`,
 * `forget` чи `finish_workout`. Але той самий рядок ішов і людині: у тост
 * відкату, у фолбек-підпис картки дії й у рядок «✓ …» для інструментів без
 * картки, тож після «запиши каву» на екрані стояв `m_84920a0a-…`. Вирізаємо
 * id саме на межі показу, а не у виконавці: модель свій id має отримувати й
 * далі.
 *
 * Форми, які пишуть виконавці (`chatActions/**`):
 *   - `… (id:m_1)` / `… (tx:m_1)` — окремі дужки;
 *   - `… (Інше, id:5c47…)` — id останнім у дужках з іншим вмістом.
 */

// `(id:…)` / `(tx:…)` цілими дужками разом із пробілом перед ними.
const STANDALONE_ID_RE = /\s*\((?:id|tx):[^)]*\)/g;
// `, id:…` усередині дужок, де до нього є людський вміст.
const TRAILING_ID_RE = /,\s*(?:id|tx):[^,)]*(?=\))/g;

export function stripTechnicalIds(text: string): string {
  return text.replace(STANDALONE_ID_RE, "").replace(TRAILING_ID_RE, "");
}
