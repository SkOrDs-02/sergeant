import { useAuthOptional } from "./AuthContext";

export function useHasAccount(): boolean {
  // `useAuthOptional`, а не `useAuth`: поза провайдером акаунта немає за
  // визначенням, і це саме та відповідь, яку тут треба дати. `useAuth`
  // там кидає, тобто предикат доступу валив би дерево — гейт не має
  // права бути небезпечнішим за фічу, яку він гейтить.
  const auth = useAuthOptional();
  return auth?.status === "authenticated" && Boolean(auth.user?.id);
}
