/**
 * Last validated: 2026-11-19
 * Status: Active
 *
 * Які уточнюючі питання моделі показати під аналізом фото.
 *
 * **Чому фільтр, а не лише промпт.** У картці аналізу є постійне поле
 * «Порція (г), якщо знаєш», а модель, побачивши невідому порцію, питала те
 * саме своїми словами: «Яка приблизна вага страви на тарілці?» — два поля
 * під одне число (фідбек власника 2026-11-19). Промпти `analyze-photo` і
 * `refine-photo` тепер забороняють питання про вагу, але запобіжник тримає
 * код, а не слухняність моделі (той самий принцип, що в `resolveIsFood`):
 * стара відповідь у кеші, інша модель чи просто непослух не мають
 * повертати дубль.
 *
 * AI-DANGER: фільтр живе саме на клієнті, а не в серверному нормалізаторі.
 * Серверний запобіжник `unknownMacrosAsNull` перетворює всі-чотири-нулі на
 * `null`, поки лишаються невідповіджені питання, і питання «яка порція?» —
 * якраз ознака, що модель оцінку не завершила. Вирізавши його до того
 * запобіжника, ми пропустили б нулі в журнал як «страва без калорій».
 */

/** Стільки питань картка показує й відправляє в перерахунок. */
export const MAX_PHOTO_QUESTIONS = 6;

// `\b` у JS бачить межу слова лише для ASCII, тож межу перед кириличним
// словом задає явна «не-літера або початок рядка».
const WEIGHT_QUESTION_RE =
  /(^|[^\p{L}])(ваг[аиуіо]|вазі|важит|важил|важив|грам|weigh|gram)/iu;

// «Яка порція?» / «Який розмір порції?» — та сама вага іншими словами. Але
// «скільки соусу» чи «яка олія» сюди не потрапляють: там немає слова «порці».
const PORTION_SIZE_RE =
  /(^|[^\p{L}])(як[аийо]\p{L}*|розмір\p{L}*)\s+(\p{L}+\s+){0,2}порці/iu;

/** Питання про вагу чи розмір порції — дубль поля «Порція (г)». */
export function isPortionWeightQuestion(question: string): boolean {
  return WEIGHT_QUESTION_RE.test(question) || PORTION_SIZE_RE.test(question);
}

/**
 * Питання, які показує картка і з яких перерахунок збирає `qna`. Один
 * помічник на обидва місця: якби картка фільтрувала, а перерахунок ні,
 * сховане питання поїхало б у `qna` з порожньою відповіддю (його й так
 * відсіює `.filter(answer)`, але межа в одному місці надійніша).
 */
export function visiblePhotoQuestions(
  questions: readonly unknown[] | null | undefined,
): string[] {
  if (!Array.isArray(questions)) return [];
  return questions
    .filter((q): q is string => typeof q === "string" && q.trim() !== "")
    .filter((q) => !isPortionWeightQuestion(q))
    .slice(0, MAX_PHOTO_QUESTIONS);
}
