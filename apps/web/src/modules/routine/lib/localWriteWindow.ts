/**
 * Last validated: 2026-09-15
 * Status: Active
 *
 * Вікно локального запису для «Рутини»: лічильник незавершених
 * dual-write-ів плюс епоха їх завершень.
 *
 * Навіщо це окремо від наявного seq-гварда. `sqliteReader` уже вміє не
 * давати СТАРОМУ оновленню кеша затерти новіший write-through (DCRUD-007b:
 * write-through піднімає `statePublishedSeq`, і оновлення, видане раніше,
 * мовчки викидає свій результат). Той гвард рахує порядок ВИДАЧІ, і саме
 * тому він не рятує від випадку нижче:
 *
 *   1. людина створює звичку — write-through кладе її в теплий кеш;
 *   2. dual-write ще летить у SQLite;
 *   3. стартує оновлення кеша — воно НОВІШЕ за write-through за порядком
 *      видачі, тож гвард його пропускає;
 *   4. читає воно порожню базу, бо вставка ще не дійшла, і публікує нуль
 *      звичок.
 *
 * Далі все тихо: звичка зникає зі стану, перейменування застосовується до
 * порожнього списку й не дає жодної операції, а `HabitDetailSheet` показує
 * стару назву через міст `lastGoodHabit`. Людина бачить створену звичку,
 * потім її назва перестає оновлюватись, потім вона пропадає.
 *
 * Заміри 2026-09-15 на гейті `deep-module-crud › routine`:
 * `routineWriteThrough seq=1 habits=1` → `routineRefresh seq=2 published=1
 * habits=0` (публікує) → `routineDualwrite applied 2` — вставка дійшла вже
 * після того, як її результат затерли нулем.
 *
 * Тому потрібен не порядок видачі, а причинність: знімок, прочитаний доки
 * бодай один локальний запис у польоті, СТАРШИЙ за оптимістичний стан, хай
 * коли б його видали. `sqliteReader` звіряє епоху до і після читання й
 * відкидає такий знімок — наступне оновлення (те, що йде одразу за
 * `applyRoutineDualWriteOps`) публікує вже повну картину.
 *
 * Чому це не спрацьовувало на `kvvfs`: там уся вистава вкладалась в один
 * тік і крок 3 просто не встигав вклинитись між 1 і 4. Гонка була завжди —
 * база в OPFS лише розсунула її на видиму ширину.
 *
 * Свідомий компроміс: відкинутий знімок НЕ перечитується. Поки людина пише
 * без упину, теплий кеш тримає її власний стан (тобто екран правдивий), а
 * зміни з іншого пристрою чекають наступного pull-у. Ціна — затримка
 * чужих змін; альтернатива — втрата своїх, і вона гірша. Якщо колись
 * знадобиться і те, і те, правильне місце — повтор читання після того, як
 * `pending` впав до нуля, а не послаблення цього гварда.
 */

let pending = 0;
let epoch = 0;

/** Викликається, коли dual-write стає в чергу. */
export function beginRoutineLocalWrite(): void {
  pending += 1;
}

/** Викликається, коли dual-write завершився — успіхом чи ні. */
export function endRoutineLocalWrite(): void {
  pending = Math.max(0, pending - 1);
  epoch += 1;
}

/**
 * Знімок стану вікна для читача. Порівнюється до й після читання:
 * `pending > 0` з будь-якого боку або зсув `epoch` означають, що знімок
 * причинно застарілий.
 */
export interface RoutineLocalWriteMark {
  readonly pending: number;
  readonly epoch: number;
}

export function markRoutineLocalWrites(): RoutineLocalWriteMark {
  return { pending, epoch };
}

/** `true`, якщо між міткою і зараз міг статись локальний запис. */
export function routineLocalWritesMoved(mark: RoutineLocalWriteMark): boolean {
  return mark.pending > 0 || pending > 0 || epoch !== mark.epoch;
}

/** Test-only escape hatch. */
export function __resetRoutineLocalWriteWindowForTests(): void {
  pending = 0;
  epoch = 0;
}
