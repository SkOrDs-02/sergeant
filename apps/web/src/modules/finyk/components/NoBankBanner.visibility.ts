/**
 * Чи показувати банер «підключити банк».
 *
 * Винесено з `FinykApp` окремою чистою функцією, бо інакше умову не було б
 * чим закрити: моки `FinykApp.extra.test.tsx` роблять сам банер
 * недосяжним, тож тест «у демо банер не показується» був би зеленим
 * незалежно від умови — порожній пін, який виглядає як захист.
 *
 * Третім прапорцем тут був `inDemo` (PR-F5, 2026-09-14): демо-сідер писав
 * `FINYK_MANUAL_ONLY_KEY`, тобто робив за людину вибір «без банку»
 * назавжди, і банер доводилось ховати окремою умовою. Демо-режим знято
 * 2026-09-17 — умова пішла разом із ним.
 */
/** Скільки днів банер мовчить після закриття (рішення власника 2026-09-30). */
export const BANK_BANNER_SNOOZE_DAYS = 7;
const DAY_MS = 24 * 60 * 60 * 1000;

// ponytail: фіксований поріг; якщо стане сигналом продукту, винести в канон.
const MANUAL_ENOUGH = 5;

export function shouldShowNoBankBanner(params: {
  hasConnectedProvider: boolean;
  manualOnly: boolean;
  /**
   * Скільки ручних витрат уже записано. Людина, що веде облік вручну,
   * вибір «банк чи вручну» вже зробила ділом, навіть не натиснувши
   * «Без банку»: після 106 записів банер питав те саме (критика екранів
   * 2026-09-25).
   */
  manualExpenseCount: number;
  /** Epoch ms останнього закриття банера; `null` — не закривали. */
  dismissedAt: number | null;
  /** Поточний час (ін'єкція заради тестів). */
  now: number;
  /** Активна вкладка Фініка (`NAV_IDS` у `FinykApp`). */
  page: string;
}): boolean {
  if (params.hasConnectedProvider) return false;
  if (params.manualOnly) return false;
  if (params.manualExpenseCount >= MANUAL_ENOUGH) return false;
  // Закритий банер повертається через N днів. `now` у застосунку оновлює
  // `useBankBannerClock`, а щойно записана позначка може бути трохи «в
  // майбутньому»: різниця від'ємна, і банер справедливо ховається.
  if (
    params.dismissedAt !== null &&
    params.now - params.dismissedAt < BANK_BANNER_SNOOZE_DAYS * DAY_MS
  ) {
    return false;
  }
  // Лише Огляд: на mobile банер займав ~37% першого екрана кожної вкладки,
  // і порожній стан вкладки опинявся під згином (критика екранів
  // 2026-09-23). Вибір «банк чи вручну» робиться один раз.
  return params.page === "overview";
}
