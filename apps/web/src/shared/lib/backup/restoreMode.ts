/**
 * Режим відновлення з файлу резервної копії Hub.
 *
 * AI-CONTEXT: restore ходить тим самим dual-write шляхом, що й звичайний
 * запис, а той шле на сервер КОЖНУ локальну зміну, зокрема видалення. Тому
 * «замінити» (рядки, яких немає у файлі, гаснуть) означає tombstone-и в
 * акаунті й на всіх пристроях, а не лише на цьому (аудит 2026-10-01, data-06).
 *
 *  - `merge` (дефолт): лише додати відсутнє. Рядок, який уже є на пристрої,
 *    лишається таким, яким був (файл не перебиває новіших правок), а рядки,
 *    яких немає у файлі, не чіпаються. Видалень не породжує.
 *  - `replace`: явний вибір людини. Усе, чого немає у файлі, видаляється й
 *    на сервері, і на інших пристроях; перед цим панель зберігає знімок.
 */
export type BackupRestoreMode = "merge" | "replace";

/**
 * Поточні елементи + елементи файлу, ключ яких ще не зустрічався.
 * Порядок: спершу поточні. Дублікати ключів усередині самого файлу
 * відкидаються (перший виграє), щоб один рядок не потрапив двічі.
 */
export function addMissingBy<T>(
  current: readonly T[],
  incoming: readonly T[],
  key: (item: T) => string,
): T[] {
  const seen = new Set<string>();
  const out: T[] = [];
  for (const item of current) {
    seen.add(key(item));
    out.push(item);
  }
  for (const item of incoming) {
    const k = key(item);
    if (seen.has(k)) continue;
    seen.add(k);
    out.push(item);
  }
  return out;
}

