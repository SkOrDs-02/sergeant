/**
 * Last validated: 2026-08-23
 * Status: Active
 *
 * Скільки ЦІЛИХ календарних діб минуло від моменту до «зараз».
 *
 * AI-CONTEXT: одна поверхня хаба показувала два різні числа для однієї й
 * тієї самої паузи в залі — «15 днів» у картці «Що зараз важливо»
 * (`core/lib/recommendationEngine.ts`) і «16 днів» у блоці інсайтів
 * (`modules/fizruk/hooks/useRestDayOverdueInsight.ts`), в один момент, для
 * одного користувача (browser QA 2026-08-23). Причина — дві різні
 * арифметики: рушій рекомендацій ділив ГОДИНИ на 24 і округляв
 * (`Math.round(hoursAgo / 24)`), інсайт рахував різницю календарних діб.
 * Тренування, що завершилось увечері, дає 15.46 доби → `round` → 15, тоді
 * як календарно це вже 16-й день. Правильна відповідь — календарна: людина
 * рахує дні по календарю, а не по 24-годинних інтервалах.
 *
 * Межа доби — ГОДИННИК ПРИСТРОЮ (ADR-0078): це клієнтська
 * re-engagement-евристика особистої доби, а не серверний фінансовий період,
 * тож київський якір тут був би неправильним.
 */

const MS_PER_DAY = 24 * 60 * 60 * 1000;

/**
 * Кількість цілих діб між днем `pastMs` і днем `nowMs` за локальним
 * календарем. Обидві сторони зрізаються до локальної півночі, тож
 * «завершив о 23:55, дивлюсь о 00:05 наступного дня» — це 1 день, а не 0.
 *
 * Повертає `Infinity`, якщо момент невідомий (`null` / нечислове /
 * непарсабельний ISO) — викликач сам вирішує, чи це «ніколи не було»
 * (мовчати), чи «дуже давно». Майбутній момент дає відʼємне число —
 * навмисно не затискаємо в нуль, щоб зіпсовані дані було видно.
 */
export function wholeDaysSince(
  past: string | number | Date | null | undefined,
  now: Date = new Date(),
): number {
  const pastMs =
    past instanceof Date
      ? past.getTime()
      : typeof past === "number"
        ? past
        : typeof past === "string"
          ? Date.parse(past)
          : NaN;
  if (!Number.isFinite(pastMs)) return Infinity;

  const todayStart = new Date(now.getTime());
  todayStart.setHours(0, 0, 0, 0);
  const pastStart = new Date(pastMs);
  pastStart.setHours(0, 0, 0, 0);

  // `round`, не `floor`: обидві сторони вже зрізані до локальної півночі,
  // тож різниця — рівно N діб ± година на переході літнього часу. `floor`
  // на «мінус година» перетворив би 15 днів на 14 двічі на рік.
  return Math.round((todayStart.getTime() - pastStart.getTime()) / MS_PER_DAY);
}
