/**
 * Last validated: 2026-11-19
 * Status: Active
 *
 * Кнопка, яку тапають, поки в полі вводу відкрита софт-клавіатура, і яка
 * НЕ мусить забирати з поля фокус.
 *
 * **Чому інакше тап губиться.** Відступ аркуша під клавіатуру
 * (`softKeyboardGapPx` → `useVisualKeyboardInset` → `Sheet`) скидається в
 * нуль синхронно, щойно фокус покидає поле, тобто на `focusout` — а той
 * настає на `mousedown` того самого тапу. Короткий аркуш (форма комори)
 * падає на висоту клавіатури ще до `mouseup`, відпускання влучає вже в інше
 * місце, і `click` не доходить до кнопки. Другий тап спрацьовує, бо
 * клавіатура вже закрита: рівно «не завжди реагує на клік» і «модалка
 * стрибає» з фідбеку власника 2026-11-19 (комора, «По одному» → «Списком»).
 *
 * `preventDefault` на `mousedown` скасовує зміну фокуса: поле лишається
 * сфокусованим, клавіатура відкритою, аркуш нерухомим, `click` влучає. Той
 * самий прийом уже стоїть на підказках продавців Фініка
 * (`ManualExpenseDescriptionSection`). Клавіатуру й скрінрідер не чіпає:
 * вони кнопки мишею не натискають.
 *
 * Якщо після дії клавіатура заважає (відкривається інший оверлей чи
 * превʼю, яке вона накрила б), сховай її В САМОМУ обробнику `click` через
 * {@link blurActiveField}: тап уже зарахований, і стрибок аркуша після
 * нього нічого не ламає.
 */
import type { MouseEvent } from "react";
import { isTextEntryElement } from "@shared/lib/platform/softKeyboard";

/** Пропси для кнопки, натискання якої не забирає фокус із поля вводу. */
export const keepFieldFocusProps = {
  onMouseDown: (event: MouseEvent<HTMLElement>) => event.preventDefault(),
} as const;

/** Ховає софт-клавіатуру: знімає фокус з активного поля, якщо він у полі. */
export function blurActiveField(): void {
  // Той самий предикат «поле вводу», що й у детекторі клавіатури: одне
  // визначення на всіх (`softKeyboard.ts`).
  const el = document.activeElement;
  if (isTextEntryElement(el)) el.blur();
}
