// Єдиний реєстр відображуваних імен модулів. До цього сплеш-онбординг
// показував «Гроші / Тіло / Рутина / Їжа», а сам хаб і боттом-нав —
// «Фінік / Фізрук / Рутина / Харчування». Один обʼєкт, два імені — це
// когнітивне тертя: користувач не певен, що «Гроші» зі сплеша і «Фінік»
// на дашборді — одне й те ж. Уніфікуємо на бренд-іменах (вони й так
// лишаються на всіх модульних поверхнях), а аспіраційний опис винесено
// у `teaser` на сплеші.
//
// Тримаємо константу у `shared/lib`, щоб імпорт не тягнув за собою
// увесь onboarding-модуль.

