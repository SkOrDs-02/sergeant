/**
 * Тон приглушених тирів.
 *
 * `muted` — для чисел звичайного кольору тексту. `inherit` — для будь-якого
 * ЗАБАРВЛЕНОГО числа (успіх, небезпека, hero-ink на градієнті): тири беруть
 * той самий колір і гасяться прозорістю, тож тир не може розійтися з
 * числом — він і є число, тільки тихіше.
 */
export type NumberTone = "muted" | "inherit";

// AI-DANGER: (2026-10-01, аудит контрасту, A5) `inherit` БІЛЬШЕ НЕ гасить
// тир прозорістю. `opacity-65` на `+` / `₴` / `,50` забарвленої суми давала
// 3.14-3.84:1 (світла) і 3.16-4.18:1 (темна) при порозі 4.5:1 — а прозорість
// на тексті множить колір на альфу предка, тож ТОКЕНУ, який можна було б
// підняти, тут нема. Тиху ієрархію тримають розмір (0.64-0.78em) і вага
// (`font-normal` проти жирної суми), а не колір. `muted` лишається: це
// окремий токен `text-muted` (≥4.5 на всіх поверхнях за `contrast.test.js`).
export const NUMBER_TONE_CLASS: Record<NumberTone, string> = {
  muted: "text-muted",
  inherit: "",
};

/**
 * Знак: U+2212, не дефіс — інакше рядки з мінусом зʼїжджають у стовпчику.
 */
export const TIER_SIGN = "text-[0.78em] font-normal";

/**
 * Символ валюти або одиниця виміру. Найбільший із приглушених тирів: `₴`
 * у більшості шрифтів має малу x-висоту й на менших кеглях зникає.
 */
export const TIER_UNIT = "text-[0.72em] font-normal";

/**
 * Копійки. Найменший тир — і він НАВМИСНО не застосовується до дробової
 * частини вимірів (див. `Measure`): копійка — сота частка гривні, тоді як
 * 0,5 кг — це пʼята частина 2,5 кг.
 */
export const TIER_FRACTION = "text-[0.64em] font-normal";
