/**
 * Last validated: 2026-08-05
 * Status: Active
 *
 * `Money` / `Delta` — типографіка чисел (анти-слоп П4,
 * `docs/05-design/design/anti-slop-strategy.md` §4/П4).
 *
 * Sergeant — продукт про числа: гривні, копійки, кілокалорії, кілограми,
 * дні. Власне трактування числа — найдешевша і найстійкіша відмінність,
 * бо вона видна на кожному екрані і не копіюється скріншотом: конкурент
 * бачить результат, але не бачить правила.
 *
 * Правило тут одне й просте: **сума домінує, решта прислуговує**.
 *
 *   −1 250,50 ₴
 *   │ └─┬──┘└┬┘└┬┘
 *   │   │    │  └─ символ: 0.72em, приглушений — валюта та сама на всьому
 *   │   │    │     екрані, тож повторювати її на повну силу — шум
 *   │   │    └──── копійки: 0.64em, приглушені — окремий тир, бо в житті
 *   │   │          вони майже ніколи не важать так, як гривні
 *   │   └───────── гривні: повний кегль і вага — це і є число
 *   └───────────── знак: 0.78em, приглушений; U+2212, не дефіс, щоб рядки
 *                  в стовпчику не зʼїжджали
 *
 * Числа тут не «на око однакові»: символ найбільший із трьох, бо ₴ у
 * більшості шрифтів має малу x-висоту і на 0.62em просто зникає в підписі;
 * копійки найменші, бо їх читають рідше за все. Перевірено рендером.
 *
 * AI-CONTEXT: розмір тирів заданий в `em`, а не в токенах шкали. Це
 * навмисно — компонент має лягати й у hero-число, і в підпис таблиці,
 * успадковуючи кегль від контейнера. Викликач ставить `text-style-*` на
 * `className`, а пропорції всередині лишаються тими самими. Токенна шкала
 * тут дала б два розміри, які треба тримати в парі вручну.
 *
 * `tabular-nums` — не косметика: без нього цифри різної ширини «дихають»
 * при кожному оновленні суми, і колонка чисел перестає бути колонкою.
 */
import {
  splitMoneyParts,
  NARROW_NBSP,
  type FormatMoneyOptions,
} from "@sergeant/shared";
import { cn } from "@shared/lib/ui/cn";
import { signedDeltaClass } from "@shared/lib/ui/amountTone";
import {
  NUMBER_TONE_CLASS,
  TIER_FRACTION,
  TIER_SIGN,
  TIER_UNIT,
  type NumberTone,
} from "./numberTiers";

/**
 * Тон приглушених тирів.
 *
 * AI-CONTEXT: тонів рівно два, і це навмисно — детально в `numberTiers.ts`,
 * звідки шкалу бере й `Measure`. До спільного файлу кожна поверхня
 * вигадувала свій приглушений колір символу (`text-brand-700
 * dark:text-success/70` в одному місці, `text-muted` в сусідньому), і та
 * сама роль виглядала по-різному.
 *
 * Псевдонім, а не власний тип: назва `MoneyTone` лишається в публічному
 * API компонента, але визначення одне на всі носії числа.
 */
export type MoneyTone = NumberTone;

export interface MoneyProps extends FormatMoneyOptions {
  /** Сума в гривнях (не в копійках). */
  amount: number;
  /**
   * Показувати копійки. За замовчуванням — ні: на більшості поверхонь
   * вони шум. Вмикай там, де копійка є частиною факту (розділення чека,
   * борг, точний залишок).
   */
  kopecks?: boolean;
  tone?: MoneyTone;
  /**
   * Оживити суму при появі — КАСКАДОМ ТИРІВ (анти-слоп П5, рішення
   * власника 2026-08-06 на `mockups/product/motion.html`, варіант C).
   *
   * Число зʼявляється відразу, тири вступають за вагою: гривні → копійки
   * → символ, крок 60 ms.
   *
   * AI-CONTEXT: до 2026-08-06 тут крутився лічильник (`CounterReveal`).
   * Замінено не через смак: каскад ЧИТАЄ ієрархію, яку вже збудував П4,
   * тобто типографіка й рух кажуть одне й те саме. Лічильник же виглядає
   * однаково в будь-якому дашборді — це рух без підпису.
   *
   * `CounterReveal` лишається для БЕЗ-тирних чисел (hero-лічильники
   * Рутини, ккал): у них нема чому каскадувати, і там відлік доречний.
   * Це не дві мови руху, а одне правило — рух читає структуру числа.
   *
   * Hard Rule #17 — анімована сума займає слот ambient-motion на екрані.
   */
  animate?: boolean;
  className?: string;
}

/**
 * Сума з розділенням на тири. Один DOM-вузол на частину, тож рядок
 * лишається виділюваним і копіюється як звичайний текст.
 */
export function Money({
  amount,
  kopecks = false,
  tone = "muted",
  animate = false,
  className,
  ...opts
}: MoneyProps) {
  const fractionOpts = {
    ...opts,
    minFractionDigits: opts.minFractionDigits ?? (kopecks ? 2 : 0),
  };
  const parts = splitMoneyParts(amount, fractionOpts);
  const muted = NUMBER_TONE_CLASS[tone];
  // Знак іде разом із гривнями: він частина того, що читають першим —
  // величини. Окремим щаблем каскаду він був би дрібнотою, яка вступає
  // «сама по собі».
  const tier1 = animate ? "money-tier" : undefined;
  const tier2 = animate ? "money-tier money-tier-2" : undefined;
  const tier3 = animate ? "money-tier money-tier-3" : undefined;

  return (
    <span className={cn("tabular-nums whitespace-nowrap", className)}>
      {parts.sign !== "" && (
        <span className={cn(TIER_SIGN, muted, tier1)}>{parts.sign}</span>
      )}
      {animate ? <span className={tier1}>{parts.integer}</span> : parts.integer}
      {parts.fraction !== "" && (
        <span className={cn(TIER_FRACTION, muted, tier2)}>
          {parts.decimalSeparator}
          {parts.fraction}
        </span>
      )}
      {/* `NARROW_NBSP` константою, а не JSX-пробілом: `{" "}` схлопується
          разом із відступами розмітки, і символ прилипає до суми впритул.
          Перевірено рендером — на око дрібниця, у наборі помітна.

          Порожній `symbol` пропускає весь вузол. Це не мікрооптимізація:
          інакше в розмітці лишався б самотній U+202F — привид пробілу,
          який нічого не відділяє. Вживається там, де символ стоїть один
          раз на пару чисел («сплачено 1 000 з 5 000 ₴»): перше число
          символу не має, але тири й `tabular-nums` йому потрібні. */}
      {parts.symbol !== "" && (
        <span className={cn(TIER_UNIT, muted, tier3)}>
          {NARROW_NBSP}
          {parts.symbol}
        </span>
      )}
    </span>
  );
}

/**
 * Дельта («+340 ₴», «−12 %») як ТИПОГРАФІЧНИЙ елемент, а не бейдж.
 *
 * AI-CONTEXT: бейдж — плашка з фоном і радіусом — це дефолт кожного
 * дашборда в медіані (анти-слоп §3.2). Тут те саме повідомлення несуть
 * знак і колір, без другого прямокутника поруч із першим. Заразом бейдж
 * ламав би вирівнювання в стовпчику: у плашки своя висота й свої відступи.
 *
 * Колір НЕ вирішує, чи це добре: `+340 ₴` доходу — успіх, `+340 ₴` витрат
 * — ні. Тому семантику задає викликач через `polarity`, а не знак числа.
 */
export interface DeltaProps {
  /** Значення дельти. Знак береться з нього. */
  value: number;
  /**
   * Що означає ЗРОСТАННЯ цього числа. `positive` — зростання добре
   * (дохід, накопичення), `negative` — зростання погане (витрати, борг),
   * `neutral` — просто зміна.
   */
  polarity?: "positive" | "negative" | "neutral";
  /** Одиниця після числа. `"₴"` за замовчуванням; `"%"` для часток. */
  symbol?: string;
  kopecks?: boolean;
  className?: string;
}

export function Delta({
  value,
  polarity = "neutral",
  symbol = "₴",
  kopecks = false,
  className,
}: DeltaProps) {
  const grew = value > 0;
  const colored = polarity !== "neutral" && value !== 0;
  /*
    AI-CONTEXT: колір бере `signedDeltaClass`, а не власну пару класів.
    Дельта тут фарбується за СЕНСОМ (добре/погано), а хелпер приймає
    знак — тому сенс перекладається у ±1. Виглядає кружним шляхом, але
    саме воно й потрібне: інакше в репо два визначення однієї ролі, і
    вони вже були розійшлися — хелпер дає світлому режиму `-strong`
    (WCAG-AA компаньйон), а тутешня пара давала голий `text-success`,
    тобто нижчий контраст на тому самому папері.
  */
  const toneClass = !colored
    ? "text-muted"
    : signedDeltaClass((polarity === "positive") === grew ? 1 : -1);

  return (
    <Money
      amount={value}
      signed
      kopecks={kopecks}
      symbol={symbol}
      // AI-CONTEXT: забарвлена дельта віддає тирам СВІЙ колір, а не
      // `text-muted`. Інакше знак і символ виходять сірими впритул до
      // зеленого числа — а знак тут несе половину повідомлення, і сірий
      // мінус біля червоної суми читається як чужий елемент. Нейтральна
      // дельта вже сама `text-muted`, тож там дефолтний тон правильний.
      tone={colored ? "inherit" : "muted"}
      className={cn("font-semibold", toneClass, className)}
    />
  );
}
