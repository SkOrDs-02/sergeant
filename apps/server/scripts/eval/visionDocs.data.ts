// ── Чеки ────────────────────────────────────────────────────────────

export interface ReceiptLine {
  name: string;
  /** Кількість або вага (кг) — дробова для вагових. */
  qty: number;
  /** Ціна за одиницю, копійки. */
  price: number;
  /** Знижка на позицію, копійки (додатне число), друкується окремим рядком. */
  discount?: number;
  weighted?: boolean;
}

export type ReceiptStyle =
  | "plain"
  /** Нахил, стиснення, шум, низький контраст, JPEG низької якості. */
  | "photo-bad"
  /** Обрізано знизу: підсумку на зображенні немає. */
  | "cut";

export interface ReceiptDoc {
  key: string;
  store: string;
  address: string;
  /** `YYYY-MM-DD` — день на чеку (київський, як друкує каса). */
  date: string;
  time: string;
  lines: ReceiptLine[];
  /** Готівка з решти — пастка «сума до оплати ≠ готівка». */
  cashGiven?: number;
  style: ReceiptStyle;
  /** Позиції, які суддя перевіряє поштучно (підрядок назви). */
  control: string[];
}

/** Сума рядка в копійках: як рахує каса (округлення до копійки) мінус знижка. */
export function lineSum(line: ReceiptLine): number {
  return Math.round(line.qty * line.price) - (line.discount ?? 0);
}

export function receiptTotal(doc: ReceiptDoc): number {
  return doc.lines.reduce((sum, l) => sum + lineSum(l), 0);
}

