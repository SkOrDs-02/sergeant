-- 137: `user_preferences.hub_prefs` — серверне сховище налаштувань вигляду
-- хаба, щоб вони їхали між пристроями.
--
-- Продуктовий огляд 2026-09-13, знахідка PR-S13; рішення founder-а
-- 2026-09-14 — «завести серверний канал». Пʼять тумблерів вигляду головної
-- (`calmMode`, `adaptiveBento`, `showTodayFocus`, `showInsights`,
-- `showMotivational`) жили ЛИШЕ в localStorage (`hub_prefs_v1`), тоді як
-- `PlanSection` продає cloud-sync між пристроями, а сам застосунок уже
-- синхронізує шість сусідніх ключів налаштувань. Людина, яка вимкнула
-- «Мотиваційний підпис» на телефоні, бачила його знову на ноутбуці.
--
-- Це НЕ oplog-sync сутність: жменя скалярних прапорців без крос-модульних
-- запитів, тож вона їде тим самим write-through `/api/me/preferences`, що
-- й `active_modules` (міграція 116) та `analytics`/`ai_memory` (076).
--
-- Тип `JSONB`, а не набір колонок. Причина протилежна до 116: там
-- `TEXT[]` обрано, бо перелік id закритий і відомий, а тут мішок навмисно
-- відкритий — коментар у `hubPrefs.schema.ts` прямо каже, що власники фіч
-- кладуть туди прапорці «without going through a central registry». Колонка
-- на кожен прапорець означала б міграцію на кожен новий тумблер, тобто
-- зняла б саме ту властивість, заради якої цей мішок і існує.
--
-- Ціна цього рішення чесна: `JSONB` не дає CHECK-а на форму, тож межі
-- (лише скаляри, стеля довжини ключа й кількості ключів) тримає Zod-схема
-- `/api/me/preferences`, а не БД. Це свідомий компроміс, і він описаний
-- тут, а не лише в коді, бо БД тут справді слабша сторона контракту.
--
-- Nullable і БЕЗ `DEFAULT`, точно як 116 і рівно з тієї ж причини:
-- `DEFAULT '{}'::jsonb` зробив би «сервер ще не знає налаштувань» і
-- «людина свідомо лишила все дефолтним» нерозрізненними на кожному новому
-- рядку. `NULL` = «немає серверних налаштувань, не чіпай локальні»;
-- `{}` = «налаштування є, і всі дефолтні».
--
-- Additive-only: жодного DROP, тож фази 2 (Hard Rule #4) не буде.

ALTER TABLE user_preferences
  ADD COLUMN IF NOT EXISTS hub_prefs JSONB;

-- Єдине, що БД тут може перевірити дешево: це саме обʼєкт, а не число,
-- рядок чи масив (усе це — валідний JSONB). Форму вмісту гейтить Zod.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'user_preferences_hub_prefs_object'
  ) THEN
    ALTER TABLE user_preferences
      ADD CONSTRAINT user_preferences_hub_prefs_object
        CHECK (hub_prefs IS NULL OR jsonb_typeof(hub_prefs) = 'object');
  END IF;
END $$;

COMMENT ON COLUMN user_preferences.hub_prefs IS
  'Налаштування вигляду хаба (дзеркало локального hub_prefs_v1). NULL = серверних налаштувань ще немає (клієнт лишає локальні як є); порожній обʼєкт = налаштування є і всі дефолтні. Форму вмісту (лише скаляри, стелі довжини й кількості) гейтить Zod-схема API, не БД.';
