-- Причина відписки: після `/stop` бот питає «чому?» і зберігає наступне
-- текстове повідомлення від цього чату.
-- Спека вейтліста: docs/90-work/planning/specs/telegram-waitlist.md
--
-- Чому стан «чекаю на причину» — колонка, а не окрема стейт-машина:
-- in-memory Map розсипається при рестарті контейнера, Redis тягне ще одну
-- залежність у шлях, який має працювати і без неї. Рядок вейтліста вже
-- існує на момент `/stop`, тож дописати в нього дві колонки дешевше за
-- будь-яке зовнішнє сховище стану.
--
-- Обидві колонки NULLable і додаються additive — двофазність не потрібна:
-- старий код їх просто не бачить.

ALTER TABLE telegram_waitlist
  -- Момент, коли бот поставив питання. Це і прапорець «чекаю», і час:
  -- одна колонка замість пари (bool, timestamp), яка може розʼїхатись.
  -- Знімається в NULL, щойно причина записана або людина повернулась
  -- через `/start`.
  ADD COLUMN stop_reason_awaited_at TIMESTAMPTZ,
  -- Вільний текст людини. Персональні дані — у логи не потрапляє
  -- (Hard Rule #21), читається лише руками через psql.
  ADD COLUMN stop_reason            TEXT;

COMMENT ON COLUMN telegram_waitlist.stop_reason_awaited_at IS
  'Коли бот запитав причину /stop. NOT NULL = чекаємо на текст-відповідь.';
COMMENT ON COLUMN telegram_waitlist.stop_reason IS
  'Причина відписки словами людини. Необовʼязкова: більшість не відповідає.';
