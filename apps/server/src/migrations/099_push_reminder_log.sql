-- 099_push_reminder_log.sql
--
-- Серверний журнал надісланих нагадувань — фундамент sweep-планувальника
-- (`apps/server/src/lib/reminders/`), який замінює локальні таймери у
-- сервіс-воркері.
--
-- Навіщо це взагалі. До цієї міграції нагадування про звички / їжу /
-- тренування жили ЛИШЕ у `apps/web/src/sw/reminders.ts` — ланцюжок
-- `setTimeout` усередині сервіс-воркера. Браузер вбиває неактивний SW за
-- ~30 секунд, а стан звичок приходив туди лише `postMessage`-ом з відкритої
-- сторінки і жив у памʼяті воркера. Тобто нагадування фізично не могло
-- спрацювати при закритому застосунку. Пуш про витрати працював, бо його
-- шле сервер (mono-вебхук), а не клієнт.
--
-- `dedup_key` навмисно тієї ж форми, що й `tag` нотифікації на клієнті
-- (`routine_notify_<habitId>_<HH:MM>_<dayKey>`), і це дає дві властивості:
--
--   1. UNIQUE-вставка працює як claim-before-send: кілька процесів гоняться
--      за один рядок, рівно один виграє і шле. Зворотний порядок
--      (send → log) лишав би вікно на подвійний банер.
--   2. Якщо сторінка ВІДКРИТА і локальний таймер уже показав нотифікацію з
--      тим самим `tag`, серверний пуш ЗАМІСТИТЬ її у шторці, а не покладе
--      другу. Тобто foreground-шлях і серверний шлях не дублюються навіть
--      коли спрацюють обидва.
--
-- `sent_at` потрібен для retention-прибирання, яке sweep робить сам раз на
-- добу (`pruneReminderLog`) — окремого cron-у для цього не заводимо.
--
-- Міграція чисто адитивна (Hard Rule #4): жодного ALTER / DROP над
-- існуючими таблицями.

CREATE TABLE IF NOT EXISTS push_reminder_log (
  user_id     TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  dedup_key   TEXT NOT NULL,
  module      TEXT NOT NULL,
  day_key     TEXT NOT NULL,
  sent_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, dedup_key)
);

-- Гарячий запит retention-прибирання: «усе, що старше за N діб».
-- Індекс по `day_key`, а не по `sent_at`: day_key — київський `YYYY-MM-DD`,
-- тобто рівно та вісь, якою мислить планувальник, і порівняння рядків тут
-- збігається з порівнянням дат.
CREATE INDEX IF NOT EXISTS push_reminder_log_day_idx
  ON push_reminder_log (day_key);
