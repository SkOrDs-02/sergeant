-- Мікро-опитування бети: відповіді на питання з inline-кнопками бота.
-- Спека вейтліста: docs/90-work/planning/specs/telegram-waitlist.md
--
-- Чому окрема таблиця, а не колонка в `telegram_waitlist`: за дві тижні
-- бети опитувань буде кілька («як тобі перший тиждень», «як другий»), і
-- колонка на кожне означала б міграцію на кожне питання. Рядок на пару
-- (людина, опитування) масштабується без DDL.
--
-- Звʼязку з користувачем застосунку тут свідомо НЕМАЄ: відповідності
-- `chat_id` <-> Better Auth `user_id` не існує (людина може натиснути
-- Start у боті й ніколи не зареєструватись, і навпаки). Відповіді
-- агрегуються по опитуванню, а не по профілю — для рішень бети досить.

CREATE TABLE telegram_beta_survey_responses (
  id         BIGSERIAL PRIMARY KEY,
  -- FK на вейтліст: відповісти може лише той, кому бот надіслав питання,
  -- а надсилаємо ми тільки підписникам. Без FK у таблицю могли б осісти
  -- chat_id-и з підробленого callback-а.
  chat_id    BIGINT NOT NULL
             REFERENCES telegram_waitlist (chat_id) ON DELETE CASCADE,
  -- Ідентифікатор питання (`week1`, `week2`, ...). Живе в коді бота, не в
  -- БД: питання — це текст і варіанти, а не дані.
  survey_id  TEXT   NOT NULL,
  -- Значення обраного варіанта (`1`..`5`). TEXT, а не INT: наступне
  -- опитування може бути нечисловим («що зламалось: гроші / їжа / звички»),
  -- і зміна типу колонки коштувала б двофазної міграції.
  answer     TEXT   NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Захист від повторного голосування НА РІВНІ БД, а не лише в коді.
  -- Telegram ретраїть callback-апдейт, поки не отримає 200, тож повторна
  -- вставка — штатний режим, а не аномалія. Перевірка «а чи вже голосував»
  -- окремим SELECT-ом лишила б вікно гонки між двома ретраями.
  UNIQUE (chat_id, survey_id)
);

-- Єдина аналітична вибірка: «як розподілились відповіді на це питання».
CREATE INDEX telegram_beta_survey_responses_survey_idx
  ON telegram_beta_survey_responses (survey_id, answer);
