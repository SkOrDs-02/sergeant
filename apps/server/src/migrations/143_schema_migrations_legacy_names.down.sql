-- NO_ROLLBACK: форвард прибирає з леджера дублікати, яких на здоровій базі не
-- мало бути ніколи. Чесного відкату тут не існує з двох причин, і жодна не
-- обходиться акуратнішим SQL.
--
-- По-перше, `applied_at` видалених рядків незворотний: DELETE його не зберігає,
-- а вигаданий час у леджері гірший за відсутній рядок — він виглядає як факт.
--
-- По-друге і головне: відкат мусив би ВСТАВИТИ легасі-імена, а на свіжій базі
-- (CI, локальна розробка, нове середовище) їх не було ніколи. Тобто «відкат»
-- не повертав би попередній стан, а СТВОРЮВАВ би дрейф там, де його не було, і
-- ламав би рівно той сигнал `schemaDrift.ts`, заради якого форвард і писався.
-- Down-дрил у CI прогнав би це на чистій базі й лишив її брудною.
--
-- Схему форвард не чіпає — тільки реєстр імен. Якщо колись знадобиться
-- повернути легасі-запис (наприклад для відкату на образ, що шипить старі
-- імена), робити це треба окремою міграцією з явними іменами й свідомим
-- рішенням, а не сліпим реверсом цієї.
