-- 147: `sync_op_log.tx_id` — номер транзакції, що вставила оп, для
-- вотермарку pull-а.
--
-- Проблема. `syncV2Pull` і replay SSE-стріму віддають `id > курсор ORDER BY
-- id`, а `id` (BIGSERIAL) видається на INSERT, тоді як видимість настає на
-- COMMIT. Довга транзакція (імпорт виписки в `modules/finyk/import/commit.ts`
-- тримає один BEGIN на весь батч і пише оп-и перед COMMIT) бере менші `id`,
-- а коротка транзакція push-а з телефона бере більші й комітиться першою.
-- Pull, що встиг забрати короткі оп-и, просуває курсор клієнта за межу, і
-- оп-и імпорту після свого COMMIT під `id > курсор` вже не потрапляють
-- ніколи. Розбір: docs/work/specs/tech-debt/backend.md § «Курсор pull
-- покладається на порядок BIGSERIAL».
--
-- Лікування. Pull віддає лише рядки, чия транзакція старша за найстарішу
-- ще активну транзакцію кластера:
--   tx_id < pg_snapshot_xmin(pg_current_snapshot())
-- Поки довга транзакція відкрита, pull не віддає ні її оп-и (ще не видимі),
-- ні пізніші за неї (tx_id >= xmin), тож курсор через неї не перескочить.
-- Ціна: поки відкрита старіша транзакція запису, свіжі оп-и затримуються
-- (зазвичай мілісекунди, на час великого імпорту секунди; завислу
-- транзакцію обриває idle_in_transaction_session_timeout з db.ts). Оп-и
-- запізнюються, але не губляться. xid8 64-бітний, тож порівняння без
-- wraparound, на відміну від 32-бітного `xmin` рядка.
--
-- Additive-зміна, двофазний DROP (Hard Rule #4) не потрібен. Колонка
-- nullable і додається БЕЗ дефолту, а дефолт ставиться окремим стейтментом:
-- так Postgres не переписує таблицю, а наявні рядки лишаються NULL. NULL
-- означає «записано до цієї міграції», тобто давно закомічено, і pull
-- трактує такий рядок як видимий. Стара версія app-у, що ще коротко
-- обслуговує трафік під час деплою, колонку не згадує, тож дефолт заповнює
-- її і для вставок старого коду.
ALTER TABLE sync_op_log
  ADD COLUMN IF NOT EXISTS tx_id xid8;

ALTER TABLE sync_op_log
  ALTER COLUMN tx_id SET DEFAULT pg_current_xact_id();

COMMENT ON COLUMN sync_op_log.tx_id IS
  'Транзакція, що вставила оп (pg_current_xact_id()). Pull віддає лише tx_id < pg_snapshot_xmin(pg_current_snapshot()), щоб курсор не перескакував оп-и довшої транзакції, закоміченої пізніше. NULL = рядок записано до міграції 147.';
