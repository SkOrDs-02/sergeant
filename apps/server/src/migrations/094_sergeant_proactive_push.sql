-- Передісторія: денна порада пушилась із обробника POST /api/coach/insight,
-- тобто рівно тоді, коли клієнт на передньому плані сам її запитав. Юзер
-- отримував сповіщення про текст, який у цю ж секунду читав на екрані, і по
-- одному з кожної поверхні. Правильний канал — серверний шедулер, який будить
-- ЛИШЕ тих, хто не заходить. Для цього бракувало трьох речей: знання про
-- останній візит, тексту поради поза клієнтом, і сліду вже надісланого.
--
-- Міграція повністю адитивна: дві нові таблиці плюс дві колонки з DEFAULT.
-- Жодного DROP і жодного NOT NULL на існуючих рядках, тож двофазність
-- (Hard Rule #4) тут не потрібна.

-- ── 1. Останній візит ────────────────────────────────────────────────────
--
-- Nullable навмисно. Для всіх, хто існував до цієї міграції, значення
-- невідоме, і шедулер мусить трактувати NULL як «не чіпати» — інакше в день
-- деплою кожен неактивний акаунт отримав би пуш на підставі даних, яких у нас
-- не було. Перший же автентифікований запит проставить реальне значення.
ALTER TABLE "user" ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ;

COMMENT ON COLUMN "user".last_seen_at IS
  'Останній автентифікований запит. Пишеться throttled (не частіше разу на годину на юзера) із requireSession. NULL = візитів після міграції 094 ще не було.';

-- Partial-індекс: шедулер щодня сканує саме тих, у кого значення є, і
-- відсіює NULL ще до порівняння дат. Рядків із NULL на старті більшість,
-- тож WHERE прибирає з індексу основну масу таблиці.
CREATE INDEX IF NOT EXISTS idx_user_last_seen_at
  ON "user" (last_seen_at) WHERE last_seen_at IS NOT NULL;

-- ── 2. Консерва денної поради ────────────────────────────────────────────
--
-- Сервер НЕ може згенерувати пораду самостійно: снапшот збирає клієнт зі
-- свого локального SQLite (readFinykStatsContext / getCachedFizrukSqliteState
-- / loadNutritionLog / loadRoutineState), а серверні таблиці покривають лише
-- частину модулів і лише для тих, хто синхронізується. Тому клієнт лишає
-- «консерву» під час візиту, а шедулер її переюзає.
--
-- Один рядок на юзера: історія тут не потрібна, читач завжди бере найсвіжіше.
-- generated_at, а не created_at: рішення про свіжість (TTL 48 годин) береться
-- саме за моментом генерації тексту, а не за моментом вставки рядка.
CREATE TABLE IF NOT EXISTS sergeant_nudge_cache (
  user_id      TEXT PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
  body         TEXT        NOT NULL,
  generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE sergeant_nudge_cache IS
  'Останній згенерований текст денної поради, збережений клієнтським візитом для переюзу шедулером. Консерва старша 48 годин не відправляється — замість неї йде нейтральна копія без цифр.';

-- ── 3. Слід надісланого ──────────────────────────────────────────────────
--
-- Складений PK — це і є дедуп. Другий INSERT за ту саму київську добу впаде
-- на конфлікті, тож навіть подвійний запуск воркера (рестарт, дубль-джоба,
-- дві репліки) не надішле двох сповіщень. Покладатись лише на BullMQ jobId
-- не можна: черга живе в Redis, який ми свідомо трактуємо як необов'язковий.
--
-- sent_on — DATE у КИЇВСЬКІЙ добі, не UTC. Записувач зобов'язаний привести
-- час до Europe/Kyiv перед вставкою (доменний інваріант репо).
CREATE TABLE IF NOT EXISTS sergeant_push_log (
  user_id TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
  sent_on DATE NOT NULL,
  channel TEXT NOT NULL CHECK (channel IN ('nudge', 'weekly')),
  PRIMARY KEY (user_id, sent_on, channel)
);

COMMENT ON TABLE sergeant_push_log IS
  'Аудит проактивних пушів Сержанта. Складений PK гарантує «не більше одного на (юзер, київська доба, канал)» на рівні БД, незалежно від стану черги.';

-- ── 4. Тумблер каналу ────────────────────────────────────────────────────
--
-- DEFAULT FALSE — свідомо. Жоден існуючий юзер не має отримати несподіваного
-- пуша в день деплою; канал вмикається явним opt-in у Налаштуваннях.
-- Окремо від push_notifications: той прапорець — згода на пуші взагалі, а
-- цей — на конкретний проактивний канал.
ALTER TABLE user_preferences
  ADD COLUMN IF NOT EXISTS sergeant_nudges BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN user_preferences.sergeant_nudges IS
  'Opt-in на проактивні повідомлення Сержанта. FALSE за замовчуванням, включно з новими акаунтами.';
