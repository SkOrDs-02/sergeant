-- 163_user_name_truncate_overlong.sql
--
-- Status: Active
--
-- Аудит 2026-10-01, `sec-16`: необмежене `user.name` роздувало cookie-кеш
-- сесії Better Auth (`session_data`, увесь `user` у куці) до 28-33 КБ, і
-- КОЖЕН запит браузера отримував 431. #1366 обмежив запис (`guardUserName`,
-- `MAX_USER_NAME_LENGTH = 100` в `auth/sanitizeUserName.ts`), але вже
-- збережені довгі імена лишились: такий акаунт заблокований і далі, бо
-- будь-яка нова сесія кешує той самий роздутий `user`, а виправити імʼя з
-- інтерфейсу неможливо — запит на виправлення теж отримує 431.
--
-- Лікування — обрізати збережене до тієї самої межі. Після цього акаунт
-- відновлюється сам: стара роздута кука живе до 5 хв (`cookieCache.maxAge`),
-- далі `get-session` читає БД і кешує вже коротке імʼя.
--
-- Межа 100 ДУБЛЮЄ `MAX_USER_NAME_LENGTH`; збіг стереже тест
-- `__tests__/163-user-name-truncate-overlong.test.ts`. Різниця одиниць:
-- `char_length` / `left` рахують кодові точки, а JS `length` — UTF-16. Для
-- кирилиці й латиниці це те саме; імʼя з емодзі може лишитись довшим за 100
-- у UTF-16, але все одно ≤ 400 байт, а для куки важить саме розмір.
--
-- Схему не змінює (DML без DDL, Hard Rule #4 про двофазний DROP не
-- застосовний). Ідемпотентно: повторний прогін не знаходить рядків.
-- Обрізане не відновити — down.sql свідомо no-op (див. там).

UPDATE "user"
SET name = left(name, 100),
    "updatedAt" = NOW()
WHERE char_length(name) > 100;
