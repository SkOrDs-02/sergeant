-- Робить поломку синку Сільпо ВИДИМОЮ в застосунку.
--
-- Існує через конкретну поразку. 2026-09-14 знайшлося, що синк не працював
-- два тижні: Сільпо мовчки знизили стелю `limit`, і кожен фоновий тік падав
-- валідацією. У Sentry за ці дні лягло 304 події — а в застосунку не було
-- НІЧОГО. Власник дізнався про поломку лише тоді, коли сам натиснув
-- «Оновити чеки».
--
-- Це не випадковість, а конструкція: таблиця тримала тільки `last_sync_at`,
-- і той торкався ЛИШЕ на успіху. Тобто «синк зламано» і «людина два тижні
-- не ходила в магазин» виглядали в інтерфейсі абсолютно однаково.
--
-- ЧОМУ КОД, А НЕ ТЕКСТ ПОМИЛКИ. `last_error_code` тримає НАШ код
-- (`SILPO_TOOL_ERROR`, `SILPO_SCHEMA_DRIFT`, …), а не відповідь Сільпо.
-- Текст відмови приходить із чужого сервера й може нести що завгодно,
-- аж до полів покупки — а це друга копія чекових даних у місці, де їх
-- ніхто не чекає (Hard Rule #21). Розбір причини лишається в логах і в
-- діагностиці; сюди їде рівно стільки, скільки треба, щоб показати
-- людині плашку й відрізнити «зламалось» від «нових чеків не було».
--
-- Адитивна міграція: обидві колонки nullable, без дефолтів і без
-- бекфілу. NULL читається як «провалів не було» — саме те, що треба для
-- наявних рядків.

ALTER TABLE silpo_connection
  ADD COLUMN IF NOT EXISTS last_failed_at  TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS last_error_code TEXT;

COMMENT ON COLUMN silpo_connection.last_failed_at IS
  'Момент ОСТАННЬОГО невдалого синку. Скидається в NULL при першому успішному — тобто непорожнє значення означає «зараз зламано», а не «колись ламалось».';

COMMENT ON COLUMN silpo_connection.last_error_code IS
  'Наш код помилки останнього провалу (SILPO_TOOL_ERROR, SILPO_SCHEMA_DRIFT, …). НЕ текст відповіді Сільпо: той може нести дані покупки (Hard Rule #21).';
