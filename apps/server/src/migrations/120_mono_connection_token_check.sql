-- 120: відмітка останньої перевірки живості токена Monobank.
--
-- ─── Що лікуємо ────────────────────────────────────────────────────────
--
-- `GET /api/mono/sync-state` читав ТІЛЬКИ базу і Monobank ніколи не
-- перепитував. Тому коли людина відкликає токен у застосунку Monobank,
-- наш рядок назавжди лишається `status = 'active'`: вебхук з їхнього боку
-- мертвий, подій більше не буде, а інтерфейс упевнено малює «Webhook
-- активний · N рахунків» над даними, які застигли назавжди.
--
-- Спіймано на беті 2026-08-10: тестер видалив токен у Monobank, а в
-- Налаштуваннях далі висів зелений статус із пʼятьма рахунками. Сигнал у
-- нас уже лежав у тому ж рядку — `webhook_registered_at` заповнений, а
-- `last_event_at` порожній, — ми його просто не читали.
--
-- ─── Чому окрема колонка, а не `updated_at` ────────────────────────────
--
-- `updated_at` рухає будь-який запис у рядок: перепідключення, ротація
-- ключа шифрування, зміна статусу. Троттлінг мусить спиратись на «коли ми
-- востаннє СПИТАЛИ Monobank», інакше кожна ротація ключа скидала б вікно
-- й відкривала позачерговий зовнішній виклик.
--
-- ─── Навіщо троттлінг узагалі ──────────────────────────────────────────
--
-- `personal/client-info` у Monobank лімітований 1 запитом на 60 секунд на
-- токен. На фронті `sync-state` має `staleTime: 30s` і
-- `refetchOnWindowFocus`, тож перевірка без вікна миттєво впіймала б 429 —
-- і, що гірше, зʼїла б ліміт у людини, яка саме в цю секунду намагається
-- перепідключитись. Колонка і є те вікно; самі пороги (30 хв після
-- підключення, 3 доби тиші, 6 год між перевірками) живуть в одному SELECT
-- у `modules/mono/connection.ts`, щоб читались разом.

ALTER TABLE mono_connection
  ADD COLUMN last_token_check_at TIMESTAMPTZ;

COMMENT ON COLUMN mono_connection.last_token_check_at IS
  'Коли сервер востаннє питав Monobank personal/client-info, щоб перевірити, чи токен ще живий (GET /api/mono/sync-state). NULL — не перевіряли жодного разу. Троттлінг: не частіше ніж раз на 6 год і лише для підозрілих підключень (вебхук зареєстровано >30 хв тому, подій нема >3 діб) — client-info лімітований 1 запитом/60 с на токен.';
