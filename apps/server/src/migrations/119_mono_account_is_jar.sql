-- 119: позначити рядки `mono_account`, які насправді є банками ("jars"),
-- а не картками.
--
-- ─── Звідки беруться такі рядки ────────────────────────────────────────
--
-- `mono_transaction.mono_account_id` має FK на `mono_account`. Коли
-- Monobank доставляє вебхуком транзакцію по рахунку, якого ми ще не
-- бачили в client-info, upsert падає з 23503, і обробник
-- (`modules/mono/webhook.ts`) створює заглушку в `mono_account` — інакше
-- транзакцію нікуди записати, а 500 у відповідь деактивує вебхук.
--
-- Проблема в тому, що банка в Monobank теж має власний рахунковий id і
-- теж генерує statement-items. Заглушка для банки лягала в таблицю
-- КАРТОК, і далі:
--   * `GET /api/mono/accounts` віддавав її як картку (`type` NULL →
--     UI малює безіменну «Картка / Monobank»);
--   * `getMonoOwnFunds` бачив `credit_limit` NULL і зараховував сирий
--     баланс банки у капітал;
--   * та сама банка ще раз потрапляла в капітал через `sumJarsUAH`
--     (`packages/finyk-domain/src/domain/assets/aggregates.ts`).
-- Тобто баланс кожної банки, у яку був бодай один переказ, рахувався
-- ДВІЧІ, а в списку карток висів привид. Знахідка founder-а 2026-08-10.
--
-- ─── Чому колонка, а не `type = 'jar'` ─────────────────────────────────
--
-- `type` — дзеркало однойменного поля Monobank (`black`/`white`/`fop`/…).
-- Записувати туди власний маркер означало б збрехати про зовнішнє API і
-- зламати будь-якого майбутнього читача, що звіряє `type` з докою Mono.
-- Окремий булев прапорець наш і нічого не дзеркалить.
--
-- ─── Чому не видалити заглушки ─────────────────────────────────────────
--
-- На них висять транзакції банки через FK. DELETE забрав би реальні
-- перекази з історії. Ховаємо рядок від читачів «рахунків», а самі
-- транзакції лишаються на місці й далі показуються в операціях.

ALTER TABLE mono_account
  ADD COLUMN is_jar BOOLEAN NOT NULL DEFAULT FALSE;

-- Реконсиляція вже створених привидів. Ідемпотентна; для юзерів без
-- банок — no-op. Далі те саме робить `upsertJars` на кожному
-- `/api/mono/connect` і `/api/mono/jars`, тож банка, яка потрапить у
-- `mono_jar` пізніше за свою заглушку, помітиться сама.
UPDATE mono_account a
   SET is_jar = TRUE
  FROM mono_jar j
 WHERE j.user_id = a.user_id
   AND j.mono_jar_id = a.mono_account_id;

COMMENT ON COLUMN mono_account.is_jar IS
  'TRUE, якщо рядок — заглушка під банку ("jar"), створена вебхуком через FK mono_transaction -> mono_account, а не справжня картка. Читачі «рахунків» (GET /api/mono/accounts, accountsCount у sync-state) такі рядки виключають, інакше баланс банки рахується двічі — і як картка, і через mono_jar. Backfill історії (modules/mono/backfill.ts) їх НЕ виключає навмисно: у банок є власна історія переказів.';
