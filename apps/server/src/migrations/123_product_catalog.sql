-- 123: product_catalog — власний каталог «штрихкод → продукт з КБЖВ».
--
-- Дослідження: docs/90-work/planning/barcode-database-research.md
--              docs/90-work/research/2026-07-25-barcode-sources-and-moderation.md
--
-- ─── Навіщо таблиця ──────────────────────────────────────────────────
--
-- До цієї міграції власної бази продуктів у Sergeant НЕ БУЛО взагалі:
-- `apps/server/src/modules/nutrition/barcode.ts` — чистий проксі-каскад
-- OFF → USDA → UPCitemdb з in-memory TTL-кешем (6 год hit / 30 хв miss),
-- який помирає разом із процесом. Кожен рестарт контейнера обнуляв усе,
-- що продукт колись дізнався про товари, і той самий штрихкод ішов у
-- зовнішні API знову. Каталог робить Tier-1 із дослідження реальним:
-- спершу дивимось у себе, і лише на miss — назовні.
--
-- Другий, не менш важливий наслідок: upstream-и мають жорсткі квоти
-- (USDA `DEMO_KEY` — 40 req/год НА ВЕСЬ ПРОДУКТ, UPCitemdb trial —
-- 100 req/добу на весь продукт). Постійне сховище перетворює ці квоти
-- з «ліміт на кожен скан» на «ліміт на кожен НОВИЙ товар», що і є
-- різницею між «сканер вимикається на десятому користувачі» і
-- «сканер працює».
--
-- ─── Чому таблиця глобальна (без user_id) ────────────────────────────
--
-- Це довідник, не дані користувача. Три наслідки, заради яких і
-- зроблено саме так:
--
--   1. ODbL. Дані Open Food Facts ліцензовані під ODbL 1.0 із
--      share-alike. Дослідження (§1, патерн Yuka) прямо радить тримати
--      OFF окремим шаром, не змішуючи з власним датасетом. Тут це
--      забезпечено структурно колонкою `source`, а не домовленістю:
--      рядки походженням 'off' завжди відокремлювані одним WHERE.
--   2. GDPR. Видалення акаунта (`gdpr_cleanup_queue`, міграція 113) не
--      має зачіпати довідник — у ньому немає нічого персонального.
--      Таблиці без user_id просто не потрапляють у cascade.
--   3. Життєвий цикл. Довідник наповнюється пакетно (посів із дампу)
--      і write-through-ом на upstream-hit; дані користувача живуть
--      через op-log CRDT. Змішування цих двох режимів в одній таблиці
--      дало б таблицю, яка не вміє жодного з них добре.
--
-- ВЛАСНІ ПРОДУКТИ КОРИСТУВАЧА свідомо НЕ в цій міграції. Модель
-- модерації внесків — відкрите рішення власника (Р-2 у
-- product-knowledge-backlog.md; рекомендація дослідження — модель
-- Cronometer, тобто внески приватні за замовчуванням). Завести схему
-- під внески зараз означало б ухвалити те рішення мовчки за власника.
-- Коли воно буде ухвалене — окрема таблиця `user_products` із user_id
-- і власним записом в `OP_LOG_TABLE_REGISTRY`, не колонка тут.
--
-- ─── Ключ: (barcode, source), без сурогатного id ─────────────────────
--
-- Первинний ключ композитний і природний. Наслідки, які варто знати:
--
--   * Один штрихкод може мати КІЛЬКА рядків — по одному на джерело.
--     Це навмисно. Джерела РЕАЛЬНО не згодні між собою: живий вимір
--     2026-08-22 на 104 штрихкодах з полиць Novus дав розбіжність по
--     калорійності >15% у 3 з 28 пар, де обидва джерела мали цифри
--     (оселедець Zigmas: OFF 330 ккал проти Listex 176). Схема, що
--     тримає один рядок на штрихкод, мусила б обрати переможця на
--     запису і НАЗАВЖДИ втратити альтернативу. Тут пріоритет джерел —
--     рішення шару читання, і його можна змінити без втрати даних.
--   * Сурогатного `BIGSERIAL id` немає навмисно: він не потрібен
--     (звертаємось завжди за штрихкодом), а його наявність втягнула б
--     Hard Rule #1 (`pg` віддає BIGINT рядком → coerce у серіалізаторі)
--     у кожного майбутнього споживача рівно ні за що.
--
-- ─── `atwater_delta_kcal` — ворота якості всередині БД ───────────────
--
-- Найважливіша колонка файлу і єдина обчислювана.
--
-- Зовнішні джерела віддають биті нутрієнти, і це не гіпотеза. У картці
-- Listex для батона «Румʼянець Молочний» (4820062051613) поля
-- переплутані місцями: `ккал/100г = 1102`, `Калорійність кДж/100г = 260`
-- — тобто в полі калорій лежать кілоджоулі. Виявлено звіркою з
-- макросами тієї ж картки: 4·7.8 + 9·1.4 + 4·54 = 259.8 ккал, і OFF
-- незалежно каже 260. По вибірці такі розходження мали 5 з 47 карток
-- з КБЖВ (11%).
--
-- `atwater_delta_kcal` — різниця між заявленою калорійністю і сумою за
-- коефіцієнтами Атвотера (4/9/4 ккал на грам білків/жирів/вуглеводів).
-- Для здорового запису вона близька до нуля; для батона вище — +842.
-- NULL, якщо джерело не дало бодай одного з чотирьох чисел.
--
-- Зберігаємо саме РІЗНИЦЮ, а не булеве «підозрілий», щоб поріг
-- лишався рішенням коду. Поріг — політика (його захочеться крутити),
-- різниця — факт. Булева колонка запекла б політику в схему і зробила
-- б зміну порогу міграцією. Орієнтир для читача: підозрілим варто
-- вважати |delta| > max(30 ккал, 25% від суми Атвотера).
--
-- ─── Поділ праці: CHECK проти delta ─────────────────────────────────
--
-- Ці дві механіки ловлять РІЗНЕ, і плутати їх не можна.
--
--   * CHECK-и — фізична неможливість. Відʼємні калорії, 150 г жиру в
--     100 г продукту, калорійність вища за чистий жир. Таке не буває
--     ні в якому продукті, тож рядок відхиляється на межі БД.
--   * atwater_delta_kcal — можливо, але не сходиться. 400 заявлених
--     ккал при 250 за макросами: обидва числа правдоподібні, але
--     разом вони неправдиві. БД такий рядок ПРИЙМАЄ і позначає; кого
--     показати користувачу — вирішує шар читання.
--
-- Практичний наслідок для писаря. Перевірено на живому Postgres:
-- переплутані кДж/ккал дають ОБИДВА сигнали одночасно — батон
-- «Румʼянець» з 1102 у полі ккал і CHECK порушує (понад стелю
-- їстівного), і delta має +842. Тобто INSERT такого рядка ВПАДЕ, а не
-- збережеться з позначкою. Це навмисно: нормалізатор зобовʼязаний
-- розпізнати підміну одиниць (ознака — kcal ≈ 4.184 × сума Атвотера)
-- і або перевести кілоджоулі в калорії, або лишити kcal_100g порожнім,
-- зберігши решту полів. Викидати весь товар через одне зіпсоване поле
-- не можна — назва, штрихкод і макроси в тій самій картці справні.
--
-- І окремо: CHECK ловить НЕ ВСІ підміни одиниць. Молоко з 53 ккал має
-- 221 кДж — обидва числа нижчі за стелю, тож підміна пройшла б CHECK
-- непоміченою. Ловить її саме delta. Тому потрібні обидві механіки, і
-- жодна не замінює другу.
--
-- ─── Пошук за назвою і чому НЕ через lower() ─────────────────────────
--
-- `pg_trgm` + GIN — щоб каталог обслуговував не лише скан штрихкоду, а
-- й пошук їжі текстом (сьогодні це окремий проксі в `food-search.ts`,
-- який ходить у ті самі OFF/USDA). Розширення стандартне і присутнє в
-- образі `pgvector/pgvector:pg17`, який репо вже використовує; той
-- самий патерн, що `CREATE EXTENSION vector` у міграції 025.
--
-- А ось індексувати `lower(name)` НЕ МОЖНА, і це не стилістика.
-- `lower()` у Postgres згортає регістр за колацією БАЗИ, а в локалі
-- C/POSIX вона згортає лише ASCII. Перевірено на живому Postgres 16:
--
--     lower('MILK')       → 'milk'        ✔
--     lower('Яготинське') → 'Яготинське'  �‼ (без змін)
--
-- Для каталогу, де більшість назв кирилицею, це означало б пошук, який
-- мовчки не знаходить половину бази — не падає, не попереджає, просто
-- повертає порожньо. Локаль продової бази задає Coolify при створенні
-- ресурсу, і з робочої машини вона недосяжна (apps/server/AGENTS.md),
-- тобто ми НЕ МОЖЕМО на неї покластися.
--
-- Тому пошуковий ключ рахує застосунок і кладе в `name_norm`. JS
-- `toLowerCase()` згортає Unicode правильно за будь-якої локалі БД, і
-- схема більше не залежить від того, як провіженили кластер. Варіант
-- «прибити ICU-колацію в індексі» відкинуто: індекс тоді залежить від
-- версії ICU і потребує перебудови на її апгрейді — зайва операційна
-- крихкість там, де достатньо порахувати рядок на запису.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS product_catalog (
  barcode             TEXT NOT NULL,
  source              TEXT NOT NULL,

  name                TEXT NOT NULL,

  -- Пошуковий ключ, який рахує ЗАСТОСУНОК, а не БД (чому — див. шапку).
  -- Канонічна нормалізація — `normText` з
  -- apps/web/src/modules/nutrition/lib/foodDb/foodDb.ts:
  --   trim → toLowerCase → уніфікація апострофів (’ ' → ') → стиснення
  --   пробілів. Той самий рядок, що вже лягає у `FoodProduct.norm` на
  --   клієнті, тож збіги між каталогом і локальною базою поводяться
  --   однаково.
  -- Як і там, у ключ входить назва РАЗОМ із брендом: людина шукає
  -- «яготинське молоко», а не окремо поле name.
  name_norm           TEXT NOT NULL,

  brand               TEXT,
  quantity            TEXT,

  -- Основні макроси на 100 г / 100 мл.
  kcal_100g           REAL,
  protein_100g        REAL,
  fat_100g            REAL,
  carbs_100g          REAL,

  -- Розширені нутрієнти: і OFF, і Listex віддають їх регулярно.
  -- Nullable без винятку — жодне джерело не гарантує повноти.
  fiber_100g          REAL,
  sugars_100g         REAL,
  saturated_fat_100g  REAL,
  salt_100g           REAL,

  -- Порція. `serving_size` — як на упаковці ("1 склянка (250 мл)"),
  -- `serving_grams` — те саме числом, коли джерело його дало.
  -- Дзеркалить BarcodeProductSchema (packages/shared/src/schemas/nutrition.ts).
  serving_size        TEXT,
  serving_grams       REAL,

  ingredients         TEXT,
  country             TEXT,
  producer            TEXT,
  image_url           TEXT,

  -- Походження рядка. `source_ref` — URL картки або зовнішній id, щоб
  -- атрибуцію ODbL можна було проставити конкретним посиланням, а не
  -- лише назвою джерела.
  source_ref          TEXT,
  source_updated_at   TIMESTAMPTZ,
  fetched_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Без CASE навмисно: у SQL арифметика з NULL уже дає NULL, тож
  -- бракує бодай одного макроса — і delta сама стає NULL. Явний
  -- CASE був би не лише зайвим, а й шкідливим: drift-чекер схеми
  -- (scripts/check-schema-drift.mjs) розбирає CREATE TABLE регуляркою
  -- і приймав ключові слова WHEN/OR/THEN/ELSE за назви колонок.
  atwater_delta_kcal  REAL GENERATED ALWAYS AS (
    kcal_100g::double precision
    - (4 * protein_100g::double precision
       + 9 * fat_100g::double precision
       + 4 * carbs_100g::double precision)
  ) STORED,

  created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT product_catalog_pkey PRIMARY KEY (barcode, source),

  -- Джерела каталогу. 'listex' і 'user' НЕ включені навмисно: Listex
  -- чекає на ключ і відповідь про ліцензію, внески користувача — на
  -- рішення Р-2. Додавання джерела = окрема міграція, яка змінить цей
  -- CHECK; це свідомий гейт, а не недогляд.
  CONSTRAINT product_catalog_source_check
    CHECK (source IN ('off', 'usda', 'upcitemdb')),

  -- Нормалізований GTIN: лише цифри, 8..14. Нормалізація (обрізання
  -- провідного нуля GTIN-14 → EAN-13 тощо) — обовʼязок писаря; тут
  -- лише межа, що не дає потрапити сміттю на кшталт "  4820 abc".
  CONSTRAINT product_catalog_barcode_check
    CHECK (barcode ~ '^[0-9]{8,14}$'),

  CONSTRAINT product_catalog_name_check
    CHECK (length(btrim(name)) > 0),

  -- Порожній пошуковий ключ = рядок, який ніколи не знайдеться текстом.
  -- Мовчазна діра в пошуку гірша за впалий INSERT.
  CONSTRAINT product_catalog_name_norm_check
    CHECK (length(btrim(name_norm)) > 0),

  -- Фізичні межі. НЕ перевірка правдоподібності (для неї є
  -- atwater_delta_kcal), а відсіювання неможливого: жоден макрос не
  -- може важити більше за самі 100 г продукту.
  --
  -- Стеля калорійності — 1000, хоча фізичний максимум це 900 (чистий
  -- жир, 9 ккал/г). Зайві 100 — запас на округлення джерелом: олії
  -- регулярно приходять як 899…900, і різні джерела округлюють
  -- по-різному. Жорстка 900 відхиляла б справні картки олій через
  -- одиницю в останньому розряді, а це дорожче за пропуск завідомо
  -- неможливих 900…1000, яких у природі все одно немає.
  CONSTRAINT product_catalog_kcal_range_check
    CHECK (kcal_100g IS NULL OR (kcal_100g >= 0 AND kcal_100g <= 1000)),
  CONSTRAINT product_catalog_macro_range_check
    CHECK (
      (protein_100g       IS NULL OR (protein_100g       >= 0 AND protein_100g       <= 100)) AND
      (fat_100g           IS NULL OR (fat_100g           >= 0 AND fat_100g           <= 100)) AND
      (carbs_100g         IS NULL OR (carbs_100g         >= 0 AND carbs_100g         <= 100)) AND
      (fiber_100g         IS NULL OR (fiber_100g         >= 0 AND fiber_100g         <= 100)) AND
      (sugars_100g        IS NULL OR (sugars_100g        >= 0 AND sugars_100g        <= 100)) AND
      (saturated_fat_100g IS NULL OR (saturated_fat_100g >= 0 AND saturated_fat_100g <= 100)) AND
      (salt_100g          IS NULL OR (salt_100g          >= 0 AND salt_100g          <= 100))
    ),
  CONSTRAINT product_catalog_serving_grams_check
    CHECK (serving_grams IS NULL OR (serving_grams > 0 AND serving_grams <= 10000))
);

-- Головний читацький патерн: «дай усі рядки цього штрихкоду» — далі
-- шар читання обирає джерело за пріоритетом. Ведуча колонка PK це вже
-- покриває, тож окремий індекс на `barcode` НЕ створюємо.

-- Пошук їжі текстом. GIN + trigram обслуговує і LIKE '%…%', і
-- similarity()-ранжування — на відміну від btree, який допоміг би лише
-- префіксу. Індексується `name_norm` (уже нормалізований застосунком),
-- тож запит теж має шукати нормалізованим рядком, БЕЗ `lower()` і без
-- `ILIKE` — обидва потягли б за собою колацію бази, заради уникнення
-- якої колонка й заведена.
CREATE INDEX IF NOT EXISTS product_catalog_name_trgm_idx
  ON product_catalog USING GIN (name_norm gin_trgm_ops);

-- Аудит якості джерела: «покажи все, що не сходиться з макросами».
-- Партіальний — здорових рядків більшість, і тримати їх в індексі
-- немає сенсу. Поріг у предикаті НАВМИСНО ширший (30 ккал) за
-- рекомендований для читання: індекс має ловити кандидатів, а не
-- ухвалювати рішення — точний поріг застосовує запит поверх.
CREATE INDEX IF NOT EXISTS product_catalog_atwater_suspect_idx
  ON product_catalog (source, barcode)
  WHERE atwater_delta_kcal IS NOT NULL
    AND abs(atwater_delta_kcal) > 30;

-- Пакетне оновлення застарілих рядків («що ми не перечитували 90 днів»)
-- і статистика наповнення по джерелах.
CREATE INDEX IF NOT EXISTS product_catalog_source_fetched_idx
  ON product_catalog (source, fetched_at);

COMMENT ON TABLE product_catalog IS
  'Глобальний довідник «штрихкод → продукт з КБЖВ». Без user_id: це не дані користувача (наслідки — ODbL-шар для OFF, необтяженість GDPR-cascade, пакетний життєвий цикл). Один штрихкод має по рядку на кожне джерело — джерела реально не згодні між собою, і пріоритет обирає шар читання, а не запис. Дослідження: docs/90-work/planning/barcode-database-research.md.';

COMMENT ON COLUMN product_catalog.barcode IS
  'Нормалізований GTIN: лише цифри, 8..14. Нормалізацію (GTIN-14 → EAN-13 тощо) робить писар — CHECK лише не пускає нецифрове сміття. Увага: внутрішньомагазинні вагові коди (префікс 2x) сюди потрапляти НЕ мають — вони генеруються касовим терміналом конкретної мережі й не ідентифікують товар глобально (вимір 2026-08-22: 35 зі 104 позицій полиці Novus мали саме такі коди).';

COMMENT ON COLUMN product_catalog.source IS
