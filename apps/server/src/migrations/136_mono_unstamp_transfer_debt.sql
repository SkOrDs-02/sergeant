-- 136 — зняти мітку «Борги та кредити» з переказів card-to-card (MCC 4829).
--
-- Міграція 010 і вебхук стамплять `category_slug` СЕРВЕРНОЮ мапою MCC
-- (`mccCategories.ts` → `MCC_CATEGORIES` з finyk-domain). 2026-09-11 у цю
-- мапу додали 4829 («переказ коштів») як `debt`, щоб щомісячний платіж по
-- кредитці перестав падати в «Інше». Живі дані 2026-09-12 (звіт власника зі
-- скріншотом Операцій) показали ціну: Monobank стамплює 4829 БУДЬ-ЯКИЙ
-- card-to-card, тож під фільтром «Борги та кредити» опинились перекази на
-- власну картку, p2p людині на імʼя і перекази на номер картки. 4829
-- прибрано з каталогу (`packages/finyk-domain/src/constants.ts`), і нові
-- рядки більше не стамплюються.
--
-- Ця міграція лікує ті, що вже збережені: без неї веб читає `categorySlug`
-- як canonical `categoryId` (`monoTxNormalize.ts`) і показує чип «Борги та
-- кредити» вічно, бо клієнтська евристика до канонічного поля не доходить.
--
-- Три запобіжники, кожен звужує UPDATE:
--   * `category_overridden = FALSE` — ручний вибір людини недоторканний
--     (той самий інваріант, що тримає ON CONFLICT у вебхуку);
--   * `mcc = 4829` і `category_slug = 'debt'` — рядки, які отримали мітку
--     САМЕ цим кодом; 6012/6051/6099 лишаються боргом і тут не зачеплені;
--   * опис без боргового ключового слова — «Погашення наступного платежу»
--     та решта справжніх погашень лишаються `debt`, бо їх тримає власний
--     доказ, а не код переказу. Список слів дзеркалить `keywords`
--     категорії `debt` у finyk-domain.
--
-- NULL (а не 'other') — навмисно: NULL означає «сервер не вирішив», і
-- клієнт переобчислює категорію з опису/MCC своєю евристикою, як робив до
-- 2026-09-11. 'other' зафіксувало б «Інше» як рішення сервера.
--
-- Ідемпотентно: повторний прогін не знаходить рядків. Rollback —
-- `136_mono_unstamp_transfer_debt.down.sql` (свідомо no-op, див. там).

UPDATE mono_transaction
SET category_slug = NULL
WHERE mcc = 4829
  AND category_slug = 'debt'
  AND category_overridden = FALSE
  AND COALESCE(description, '') !~* '(погашення|кредит|позика|розстрочка|izibank|credit|loan|борг)';
