/**
 * Тип кейса для стенду вибору інструментів (`pnpm eval:tools`).
 *
 * Кейси живуть у `src/`, а не поряд зі скриптом, з однієї причини: їх треба
 * читати безмережевому тесту покриття (`toolCoverage.test.ts`), а скрипт
 * стенду при імпорті тягне за собою CLI-обвʼязку і виклики до OpenRouter.
 *
 * Розкладені по доменах теж навмисно - один файл на предметну область
 * означає, що кейси різних модулів можна писати паралельно, не сходячись у
 * тому самому місці.
 */

/**
 * Один наступний хід сценарію: що повертається моделі на її попередній виклик
 * і що вона має викликати після цього.
 *
 * AI-CONTEXT: `result` пише автор кейса руками, як дані. Це не мок виконавця,
 * це те, що прод повернув би моделі, тож формат тримається таким же лаконічним,
 * як вихід `toolOutputWrapping.ts`. Саме звідси береться id, який модель мусить
 * перенести в аргумент наступного виклику замість вигадати свій - те, чого
 * одноходовий стенд не міг перевірити взагалі.
 */
export interface ToolTurn {
  /** Що повертається моделі як `tool_result` на її попередній виклик. */
  result: string;
  /** Який інструмент має бути викликаний після цього результату. */
  accept: string[];
}

export interface ToolCase {
  name: string;
  user: string;
  /** Будь-який із цих інструментів зараховується як правильний вибір. */
  accept: string[];
  /**
   * Очікувані аргументи: `{ інструмент: { поле: значення } }`.
   *
   * Пишеться лише там, де правильна відповідь однозначна від фіксованої
   * «сьогодні» блоку ДАНІ (2026-07-30): «за минулий тиждень» це рівно
   * 2026-07-20..2026-07-26, «250 грн» це 250. Масив означає «будь-яке з», і
   * це форма для мапінгу категорій, де відповідь - судження, а не факт.
   *
   * Механічні перевірки (обовʼязкові поля, enum, типи, формат дати й часу,
   * неіснуючі поля) сюди НЕ пишуться: вони виводяться зі схеми інструмента і
   * діють на кожен виклик самі.
   */
  expectArgs?: Record<string, Record<string, string | number | string[]>>;
  /**
   * Продовження діалогу після першого ходу. Максимум два записи, тобто три
   * ходи разом із першим - довші ланцюжки недетерміновані настільки, що їхній
   * результат уже нічого не доводить.
   *
   * Порожнє поле означає одноходовий кейс, і таких більшість: ланцюжок
   * дописується лише там, де прод реально ходить двічі.
   */
  turns?: ToolTurn[];
  /**
   * Правильна поведінка - НЕ викликати інструмент (балачка, поза доменом,
   * деструктивна дія без підтвердження). Без цього прапорця стенд міряв лише
   * «чи обрав правильний», але не «чи втримався від виклику» - а зайвий
   * виклик у write-інструмент дорожчий за пропущений read.
   */
  expectNoTool?: boolean;
  /** Потрібні ВСІ інструменти зі списку, а не будь-який (складені прохання). */
  requireAll?: boolean;
  /**
   * Відмова словами теж зараховується.
   *
   * AI-CONTEXT: у кейсі «неіснуюча сутність» блок ДАНІ вже містить повний
   * список звичок, тож `query_habits` - зайвий рід-виклик. `glm-5.2` відповів
   * «у твоїй рутині немає медитації, створити?» і отримав MISS, хоча це краща
   * поведінка за очікувану. Пастка цього кейса - вигаданий `hab_meditation`,
   * і її ловить окремий лічильник `hallucinated`, а не цей предикат.
   */
  acceptRefusal?: boolean;
}
