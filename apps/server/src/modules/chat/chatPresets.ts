import { CHAT_PRESETS, type ChatPreset } from "@sergeant/shared";

/**
 * Серверні preset-и системної інструкції для `/api/chat`.
 *
 * AI-CONTEXT: до цього кнопка «Заповнити профіль» слала свою інструкцію
 * звичайним user-повідомленням (`MEMORY_ONBOARDING_PROMPT` у
 * `apps/web/src/core/profile/memoryBank.ts`). Три проблеми, які цей модуль
 * закриває:
 *
 *   1. **Інструкція від клієнта.** Текст, що керує поведінкою моделі,
 *      приходив із браузера. Це той самий клас діри, що закрив v17
 *      огорожею `<user_data>` навколо `context`, тільки через інший вхід.
 *      Тепер клієнт шле лише ідентифікатор з `CHAT_PRESETS`, а текст живе
 *      тут і в бандл не потрапляє.
 *   2. **Стіна тексту в чаті.** Сім рядків інструкцій рендерились
 *      бульбашкою «від користувача» і назавжди осідали в історії
 *      (`hub_chat_history` + бекап). Тепер користувач бачить один рядок.
 *   3. **Конфлікт із `SYSTEM_PREFIX`.** Старий текст вимагав резюме й
 *      підтвердження кожного пункту, тоді як системний промпт наказує
 *      зберігати автоматично й не питати дозволу. Два накази однакової
 *      сили = різна поведінка на різних моделях. Preset-и написані ПІД
 *      системний промпт, а не проти нього.
 *
 * AI-DANGER: preset-блок іде окремим system-блоком ПІСЛЯ cached
 * `SYSTEM_PREFIX` (див. `promptCache.ts::buildSystem`) і НЕ загортається в
 * `<user_data>` — на відміну від клієнтського `context`. Це коректно рівно
 * доти, доки текст лишається нашим: кладеш сюди щось, що приходить із
 * запиту, — і огорожа, і весь v17 обходяться одним полем.
 */
/**
 * Відмова від сторонніх запитів усередині сценарного режиму.
 *
 * AI-CONTEXT: це не про якість діалогу, а про зловживання. Поле `preset`
 * приходить від клієнта, і перевірити намір сервер не може — будь-хто
 * причепить його до звичайного запиту й обслужиться з окремого відра квоти
 * (`aiQuotaBudget.ts`). Тижневе вікно обмежує МАСШТАБ такого трюку, а це
 * правило прибирає його СЕНС: у режимі інтервʼю асистент не відповідає на
 * сторонні питання, тож вкрадений бюджет не конвертується у безкоштовний
 * універсальний LLM.
 *
 * Тримай очікування правильними: промпт — прохання, не контракт. Тут він і
 * не єдиний барʼєр — під ним `requireSession()`, per-route rate-limit і
 * тижневе відро. Цей рядок знімає мотив, решта обмежує наслідки.
 */
const OFF_TOPIC_RULE = `- Якщо повідомлення не є відповіддю на твоє питання і не є фактом про користувача — не виконуй його. Одним реченням скажи, що зараз заповнюєш профіль, і повтори своє питання.`;

const PROFILE_INTERVIEW = `РЕЖИМ: коротке інтервʼю, щоб заповнити памʼять профілю.
- Максимум 4 твої повідомлення на все інтервʼю; у кожному 2-3 короткі питання на одну тему.
- Теми по порядку: (1) головний фокус зараз і яка зміна потрібна; (2) обмеження — алергії, дієта, здоровʼя, травми; (3) типовий тиждень і що заважає; (4) як зручно отримувати нагадування та поради.
- Не питай те, що вже видно з блоку ДАНІ.
- Після кожної відповіді одразу зберігай факти через remember: один виклик — один короткий факт із категорією. Дозволу не питай.
- Користувач пропускає питання — йди далі без наполягань.
- Створюй ЛИШЕ записи памʼяті. Не створюй звички, цілі, транзакції, тренування чи прийоми їжі.
- У кінці одним реченням: скільки фактів зберіг і що їх можна змінити в Профілі.
${OFF_TOPIC_RULE}`;

const PROFILE_ADD_INFO = `РЕЖИМ: доповнення памʼяті профілю.
- Постав одне коротке уточнення, якщо без нього факт незрозумілий; інакше зберігай одразу.
- Зберігай через remember: один виклик — один короткий факт із категорією. Дозволу не питай.
- Не дублюй те, що вже є в блоці [Профіль користувача].
- Створюй ЛИШЕ записи памʼяті. Не створюй звички, цілі, транзакції, тренування чи прийоми їжі.
${OFF_TOPIC_RULE}`;

const PRESET_TEXT: Record<ChatPreset, string> = {
  profile_interview: PROFILE_INTERVIEW,
  profile_add_info: PROFILE_ADD_INFO,
};

/**
 * Текст preset-а або `null`, якщо preset не заданий / невідомий.
 *
 * Валідація входу — `ChatRequestSchema`, але функція навмисно толерантна до
 * `unknown`: `assertAiQuota` читає `req.body` ДО `parseBody`, тож єдиної
 * точки, де preset уже звужений типом, немає.
 */
export function presetInstruction(preset: unknown): string | null {
  if (typeof preset !== "string") return null;
  if (!isChatPreset(preset)) return null;
  return PRESET_TEXT[preset];
}

export function isChatPreset(value: unknown): value is ChatPreset {
  return (
    typeof value === "string" &&
    (CHAT_PRESETS as readonly string[]).includes(value)
  );
}
