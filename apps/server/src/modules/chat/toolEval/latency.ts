/**
 * Зведення латентності стенду вибору інструментів — усе, що не потребує мережі.
 *
 * Живе тут, а не в `scripts/tool-selection-eval.ts`, з тієї самої причини, що
 * й `scoring.ts`: `scripts/` не входить у `include` серверного tsconfig, тож
 * ані typecheck, ані vitest туди не дістають. Помилка в підрахунку хвоста
 * виглядала б як властивість моделі — рівно той клас підміни, який цей модуль
 * і має унеможливити.
 *
 * AI-CONTEXT: чому хвіст, а не медіана. До 2026-09-19 стенд не мав ані
 * таймауту, ані перцентилів — друкував саму медіану. Зависання шлюзу ставало
 * великим числом латентності, невідрізнимим від повільної моделі, і саме так
 * замір 2026-08-26 прочитав 30,6 с у `deepseek-v4-flash` як «модель повільна».
 * Прод-замір 2026-09-17 показав бімодальність (успіхи 5-8 с, збої рівно на
 * стелі), тобто ламається саме хвіст, а медіана лишається чудовою в обох
 * станах.
 */

/**
 * Перцентиль по зростаючо відсортованому масиву, метод «nearest rank».
 *
 * Без інтерполяції навмисно: на десятках спостережень вона дає хибну
 * точність, а нам потрібне РЕАЛЬНЕ спостереження — «була відповідь на стільки
 * мілісекунд», а не середнє між двома сусідніми.
 *
 * Порожній вхід дає 0: це не «швидко», а «нічого не зміряно», і читати його
 * треба разом із лічильником спроб.
 */
export function percentile(sortedAsc: readonly number[], p: number): number {
  if (sortedAsc.length === 0) return 0;
  const rank = Math.ceil((p / 100) * sortedAsc.length);
  const index = Math.min(sortedAsc.length, Math.max(1, rank)) - 1;
  return sortedAsc[index] ?? 0;
}

export interface LatencySummary {
  /** Скільки спроб узагалі зроблено, включно із зависаннями. */
  attempts: number;
  /** Скільки спроб обрізав таймаут стенду. */
  timeouts: number;
  p50: number;
  p95: number;
  max: number;
}

/**
 * Зводить латентності УСПІШНИХ спроб і окремо рахує зависання.
 *
 * AI-DANGER: не додавай сюди латентність таймаутів «щоб не губити дані».
 * Вона дорівнює стелі, а не часу відповіді — це цензуроване спостереження.
 * Підмішана в перцентилі, вона тим сильніше ЗАНИЖУЄ хвіст, чим нижча стеля:
 * опустив таймаут удвічі — і p95 «покращився», хоча зависань стало більше.
 * Саме цей самообман робить гейт непридатним для того, заради чого він є.
 */
export function summarizeLatency(
  successfulMs: readonly number[],
  attempts: number,
  timeouts: number,
): LatencySummary {
  const sorted = [...successfulMs].sort((a, b) => a - b);
  return {
    attempts,
    timeouts,
    p50: percentile(sorted, 50),
    p95: percentile(sorted, 95),
    max: sorted[sorted.length - 1] ?? 0,
  };
}
