/**
 * Суддя-модель - другий шар оцінювання стенду вибору інструментів.
 *
 * Навіщо він потрібен. Структурний суддя питає «чи є цей інструмент у списку
 * прийнятних» і на це відповідає бездоганно. Але частина промахів у записі -
 * не промахи: на «покажи статистику медитації» модель відповіла, що такої
 * звички немає, і запропонувала створити. Це краще за очікуване, а стенд
 * пише MISS. Симетрично буває й навпаки: правильний інструмент із безглуздою
 * відповіддю зараховується як влучання.
 *
 * Чого він НЕ робить. Він не гейтить. Ніколи. Він недетермінований і платний,
 * тобто має рівно ті самі дві властивості, які тримають живий RAG-прогін поза
 * PR-гейтом. Його вихід - колонка у звіті й список розбіжностей зі
 * структурним суддею; цінність саме в розбіжностях, бо кожна з них це або
 * бреха евристики, або спірний кейс.
 *
 * Вендор судді навмисно інший за підсудного: підсудний на першому ході -
 * gemini, суддя - glm. Суддя однієї родини з підсудним поділяв би з ним сліпі
 * зони й підтверджував би саме ті помилки, які треба ловити.
 */

import type { ToolCase } from "../toolSelectionCases/index.js";
import { DATA_BLOCK } from "./dataBlock.js";
import type { RecordedCase } from "./cassette.js";
import { pickedFrom } from "./scoring.js";

/** Модель судді. Інша родина, ніж прод-дефолт першого ходу. */
export const DEFAULT_JUDGE_MODEL = "z-ai/glm-5.2";

export const JUDGE_SYSTEM = `Ти оцінюєш роботу асистента, який керує застосунком через інструменти.
Тобі дають прохання користувача, дані, які асистент бачив, і те, що він зробив: виклики інструментів з аргументами і текст відповіді.

Оціни ОДНЕ: чи розумно асистент відреагував на прохання.
Розумно означає: дію користувача виконано або зроблено осмислений крок до неї (наприклад, спершу пошук потрібної сутності), аргументи відповідають проханню, а відмова доречна там, де сутності не існує або дія руйнівна.
Нерозумно означає: асистент зробив не те, вигадав дані, проігнорував частину прохання або відповів пусткою.

Формат відповіді - рівно один рядок:
ОК: <причина до 12 слів>
або
ПОГАНО: <причина до 12 слів>`;

export interface JudgeVerdict {
  ok: boolean | null;
  reason: string;
}

/**
 * Розбір відповіді судді.
 *
 * `null` означає «суддя не сказав нічого зрозумілого», і це третій стан, а не
 * синонім «погано». Змішати їх означало б повторити помилку, через яку
 * транспортні збої колись читались у звіті як провали моделі.
 */
export function parseVerdict(text: string): JudgeVerdict {
  // Шукаємо вердикт у будь-якому рядку, а не лише в першому. Перша версія
  // брала `split("\n")[0]` і віддала «без вердикту» на 37 кейсах із 81: модель
  // регулярно починає порожнім рядком або службовою фразою, а сам вердикт
  // пише нижче. Виглядало це як зламаний суддя, хоча судив він нормально.
  const lines = text
    .split("\n")
    .map((l) => l.replace(/[*_`#>]/g, "").trim())
    .filter(Boolean);
  for (const line of lines) {
    const match = /^(ОК|ПОГАНО)\s*[:\-–—]?\s*(.*)$/iu.exec(line);
    if (match) {
      return {
        ok: match[1]?.toUpperCase() === "ОК",
        reason: (match[2] ?? "").trim().slice(0, 120),
      };
    }
  }
  return {
    ok: null,
    reason: (lines[0] ?? "(порожня відповідь)").slice(0, 120),
  };
}

/** Що саме показуємо судді: прохання, контекст і фактичні дії по ходах. */
export function buildJudgePrompt(
  toolCase: ToolCase,
  recorded: RecordedCase,
): string {
  const turns = recorded.turns.map((turn, index) => {
    const picked = pickedFrom(turn.blocks);
    const text = turn.blocks
      .filter((b) => b.type === "text" && b.text)
      .map((b) => b.text as string)
      .join(" ")
      .replace(/\s+/g, " ")
      .trim();
    const fed = turn.fedResult
      ? `\n  результат інструмента: ${turn.fedResult}`
      : "";
    return [
      `Хід ${index + 1}:${fed}`,
      `  виклики: ${picked.length ? picked.join(", ") : "жодного"}`,
      `  текст: ${text || "(порожньо)"}`,
    ].join("\n");
  });

  return [
    `ДАНІ, які бачив асистент:\n${DATA_BLOCK}`,
    `\nПрохання користувача: ${toolCase.user}`,
    `\nЩо зробив асистент:\n${turns.join("\n")}`,
  ].join("\n");
}
