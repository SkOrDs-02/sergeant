export interface SurveyOption {
  /** Напис на кнопці. Telegram ріже довгі — тримаємо в межах кількох знаків. */
  label: string;
  /** Значення, що їде в `callback_data` і лягає в БД. */
  value: string;
}

export interface SurveyDefinition {
  /** Стабільний ключ питання. Він же — половина UNIQUE-ключа відповіді. */
  id: string;
  question: string;
  options: SurveyOption[];
}

