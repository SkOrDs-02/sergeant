/**
 * Тексти бота закритої бети та визначення мікро-опитувань.
 *
 * Винесено з `waitlistBot.ts` з двох причин. Перша прозаїчна: разом вони
 * пробивали ліміт `max-lines: 600` (Hard Rule #18). Друга важливіша —
 * тексти правляться незрівнянно частіше за логіку, і окремий файл робить
 * такий диф читабельним: видно, що змінилась копія, а не поведінка.
 *
 * Жодне посилання тут НЕ захардкоджене. Усі чотири приходять ззовні у
 * `BetaLinks`, який роутер збирає з env — бета живе на окремому
 * Vercel-проєкті з власним доменом (`docs/work/specs/beta-launch/run-beta-wave.md`
 * § Фаза 0.3), і зашитий URL зробив би модуль неперевикористовним уже на
 * другій хвилі.
 *
 * Копірайт за `docs/product/copy/style-guide.uk.md`: звертання на «ти»,
 * 1-а особа однини від імені бота, ніякої 1-ї множини. Дієслів у минулому
 * часі про адресата немає навмисно — інакше довелось би або писати в
 * чоловічому роді, або городити «передумав(ла)».
 */

/**
 * Зовнішні посилання бети. Порожній рядок — легальне значення: змінна може
 * бути не заданою (група ще не створена, форма ще не зроблена), і текст
 * зобовʼязаний це пережити. Кожен білдер нижче мовчки пропускає порожній
 * пункт замість того, щоб надіслати «Група бети: » у нікуди.
 */
export interface BetaLinks {
  /** Адреса застосунку бети. */
  appUrl: string;
  /** Invite-лінк у групу бети (`TELEGRAM_BETA_INVITE_LINK`). */
  groupLink: string;
  /** Контакт founder-а, разом із `@`. Лише для `/install`. */
  founderUsername: string;
}

/** Склеює лише непорожні блоки — порожній лінк не лишає діри в тексті. */
function joinBlocks(blocks: Array<string | null>): string {
  return blocks.filter((b): b is string => b !== null && b !== "").join("\n\n");
}

/**
 * Відповідь, коли адреси застосунку немає.
 *
 * Спільна для `/app` і `/install`, і це не економія рядків: обидві команди
 * без адреси відповідають на одне й те саме питання — «куди мені йти». Дати
 * на `/install` покрокову інструкцію, у якій замість адреси стоїть
 * «надішли /app», а на `/app` сказати, що адреси немає, означає замкнути
 * людину в колі з двох команд.
 *
 * Формулювання «ти вже в списку» тут несе роботу: без нього перше, що
 * робить людина, побачивши паузу, — намагається зареєструватись ще раз.
 */
const NO_APP_URL_REPLY = joinBlocks([
  "Бета зараз на паузі, доступу за посиланням немає.",
  "Готую новий раунд. Щойно відкрию набір, напишу сюди першим, " +
    "нічого робити не треба, ти вже в списку.",
]);

/** `/app` — куди йти. Коротко: довга відповідь тут нікому не потрібна. */
export function appReply(links: BetaLinks): string {
  if (!links.appUrl) return NO_APP_URL_REPLY;

  return joinBlocks([
    `Sergeant тут: ${links.appUrl}`,
    "Постав на головний екран, відкриватиметься як звичайний застосунок, " +
      "без адресного рядка й вкладок. Як саме: /install",
  ]);
}

/**
 * `/install` — інструкція PWA.
 *
 * Про iOS сказано окремо й наголошено не заради повноти. Це найдорожчий
 * розрив очікувань у бета-тесті: людина вмикає нагадування, бачить, що
 * налаштування збереглось, і робить висновок, що продукт їх «просто не
 * шле». Насправді жодна браузерна вкладка на iOS не має права будити
 * сторінку — web push там працює ЛИШЕ для застосунку, доданого на
 * початковий екран. Дешевше пояснити в інструкції, ніж розбирати по
 * одному в групі.
 *
 * Браузер для встановлення НЕ обмежуємо Safari. З iOS 16.4 «На початковий
 * екран» є і в Chrome, і в Edge, і в Firefox, і встановлений з них
 * застосунок отримує ті самі права, зокрема push. «Тільки Safari» —
 * застаріле знання, і воно коштує тестера, який Safari не тримає.
 */
export function installReply(links: BetaLinks): string {
  // Без адреси інструкція не має предмета: людині нема що відкривати, а
  // кроки «Поділитися → На початковий екран» без неї лише імітують
  // робочий шлях. Віддаємо те саме, що й `/app` — див. `NO_APP_URL_REPLY`.
  if (!links.appUrl) return NO_APP_URL_REPLY;

  const url = links.appUrl;

  return joinBlocks([
    "Як поставити Sergeant на телефон",

    "iPhone (Safari, Chrome або Firefox):\n" +
      `1. Відкрий ${url}\n` +
      "2. Тисни «Поділитися», квадрат зі стрілкою вгору\n" +
      "3. Гортай список униз → «На початковий екран»\n" +
      "4. «Додати»",

    "⚠️ На iPhone нагадування працюють ЛИШЕ у встановленому застосунку. " +
      "Це обмеження самої iOS, не наше: браузерна вкладка не має права " +
      "показувати сповіщення. Лишиш просто вкладкою, Sergeant " +
      "мовчатиме, хоч у налаштуваннях усе буде ввімкнено.",

    "Android – через Chrome:\n" +
      `1. Відкрий ${url} у Chrome\n` +
      "2. Тисни ⋮ у правому верхньому куті\n" +
      "3. «Встановити застосунок», або «Додати на головний екран»\n" +
      "4. «Встановити»",

    links.founderUsername
      ? `Не знаходиш потрібний пункт, напиши ${links.founderUsername}, розберусь.`
      : null,
  ]);
}

/**
 * `/help` — правила бети й один канал зворотного звʼязку.
 *
 * Канал рівно один — група бети. Ані in-app віджета фідбеку, ані анонімної
 * форми, ані особистого контакту тут немає: карта з кількох маршрутів
 * змушує тестера обирати, а вибір коштує повідомлення, якого потім немає.
 * Усе — баги, питання, ідеї — йде в одне місце.
 *
 * Порожній `groupLink` прибирає блок цілком: «Куди що писати:» без жодного
 * пункту гірше за його відсутність.
 */
/**
 * `inGroup` дописує рядок про те, що підписочні команди працюють лише в
 * особистих. Без нього довідка в групі перелічувала б `/stop` як робочу
 * команду, хоча вебхук її там навмисно ігнорує (`telegram-webhook.ts`,
 * allowlist групових команд) — тобто відтворювала б рівно ту саму тишу у
 * відповідь на запрошення, через яку бота й пішли перевіряти.
 */
export function helpReply(links: BetaLinks, inGroup = false): string {
  return joinBlocks([
    "Бета Sergeant: два тижні, закрите коло",

    "Правило одне: користуйся як звичайним застосунком і кажи, коли щось не так. " +
      "Мовчазна бета не дає нічого, навіть «дрібниця, але дратує» вартує повідомлення.",

    links.groupLink
      ? `Куди писати: усе (зламалось, виглядає криво, питання, ідеї) ` +
        `у групу бети: ${links.groupLink}\n\n` +
        `Про баг кажи, з якого екрана він і що ти робив перед ним, ` +
        `інакше доведеться перепитувати.`
      : null,

    "Команди бота:\n" +
      "/app: адреса застосунку\n" +
      "/install: як поставити на головний екран\n" +
      "/help: це повідомлення\n" +
      "/stop: відписатись від розсилки",

    inGroup
      ? "Тут, у групі, я відповідаю лише на /app, /install і /help. " +
        "Підписка й відписка – в особистих зі мною: розсилка йде конкретній " +
        "людині, а не чату."
      : null,
  ]);
}

