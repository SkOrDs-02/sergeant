/**
 * Відповідь тим, хто прийшов, коли черга вже довша за розмір раунду.
 *
 * Свідомо НЕ «ти не встиг». Відмова відсіює людину назавжди, а черга нам
 * потрібна: натиснути Start і реально зареєструватись у застосунку — різні
 * дії, і між ними відвал. Із запрошеного раунду доходить помітно менше, ніж
 * запрошено, тож добирати доводиться саме з черги.
 *
 * Тому називаємо номер і причину, чому він рухається — це утримує.
 *
 * **Текст переписано 2026-09-17 разом із рахунком номера.** Був такий:
 * «Перша хвиля вже заповнена, ти N-й у черзі. Напишу, щойно звільниться
 * місце». Обидва речення стали неправдою після першої бети: хвиля не
 * «заповнюється», вона вже пройшла, і місця в ній не звільняються —
 * наступний доступ це новий раунд. Номер тепер рахує лише тих, хто попереду
 * ще чекає, тож і речення навколо нього мусить говорити про раунд, а не про
 * вільне місце у вже закритому.
 */
export function startReplyQueued(position: number): string {
  return (
    `Готово, ти в списку: ${position}-й у черзі на наступний раунд.\n\n` +
    "Напишу, щойно відкрию набір: частина запрошених не доходить, " +
    "і черга рухається швидше, ніж здається.\n\n" +
    "Не актуально, надішли /stop."
  );
}

