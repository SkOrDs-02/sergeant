/**
 * Текст повідомлення після зарахованої відповіді.
 *
 * Питання лишається у тексті навмисно: за тиждень людина відкриє чат і має
 * побачити, на що саме відповіла, а не самотнє «Дякую».
 */
export function surveyAnsweredText(
  survey: SurveyDefinition,
  answerLabel: string,
): string {
  return `${survey.question}\n\n✅ Твоя відповідь: ${answerLabel}. Дякую — саме це й потрібно.`;
}

