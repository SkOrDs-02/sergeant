/**
 * Детектор «схоже на переказ між власними рахунками» для рядків імпорту
 * (виписка CSV і скрін банкінгу — спільний, бо працює з тим самим
 * людським описом операції). Follow-up founder-а 2026-08-18 після
 * перевірки реальної mono-виписки: «Поповнення «просто»» (картка → своя
 * банка) і «Часткове зняття банки «просто»» (банка → картка) — не
 * витрати/доходи, а рух між власними кишенями, і без розмітки вони
 * засмічують імпорт.
 *
 * Свідомо КОНСЕРВАТИВНИЙ curated-список патернів (легко розширюваний), а
 * не евристика: false positive лише знімає галочку за замовчуванням
 * (рядок видимий, вмикається одним тапом), але кожен патерн має бути
 * пояснюваним. Реальні формулювання з перевіреної виписки:
 *   - «Часткове зняття банки «просто»»            → переказ (income-бік)
 *   - «Поповнення «просто»»                       → переказ (expense-бік)
 *   - «Поповнення «На допомогу Єнчику» вiд Віктор К.» → НЕ переказ:
 *     « від » після назви — донат у ЧУЖУ банку, реальна витрата.
 */

const OWN_TRANSFER_PATTERNS: readonly RegExp[] = [
  // mono: банка → картка. Зняти можна лише з ВЛАСНОЇ банки, тож патерн
  // безумовний.
  /^\s*часткове зняття банки/i,
  // mono: картка → банка. Лише коли опис — РІВНО «Поповнення «назва»»
  // (лапки одразу після слова): «Поповнення картки», «Поповнення
  // рахунку», «Поповнення +380…» лапок не мають і не матчаться.
  // Виняток « від » вирізаний у isLikelyOwnTransfer.
  /^\s*поповнення\s*[«"„']/i,
  // Узагальнене банківське формулювання власного переказу
  // (mono/Privat24: «Переказ на свою картку», «Переказ зі своєї картки»).
  /переказ\s+(?:на|зі|з)\s+сво/i,
];

// « від X» після назви банки — поповнення ЧУЖОЇ банки (донат) або чуже
// поповнення твоєї: в обох випадках гроші РУХАЛИСЬ між різними людьми.
// Матчиться і латинська i («вiд» — mono реально мішає кирилицю з
// латиницею в експорті, видно в перевіреній виписці).
const FROM_SOMEONE_RE = /\s+в[іi]д\s+/i;

/** `true` — опис схожий на переказ між власними рахунками/банками. */
export function isLikelyOwnTransfer(description: string): boolean {
  const d = description.trim();
  if (!d) return false;
  if (/^\s*поповнення/i.test(d) && FROM_SOMEONE_RE.test(d)) return false;
  return OWN_TRANSFER_PATTERNS.some((re) => re.test(d));
}
