import { describe, expect, it } from "vitest";
import { isLikelyOwnTransfer } from "./transferDetect.js";

describe("isLikelyOwnTransfer", () => {
  // Формулювання — з реальної mono-виписки, перевіреної 2026-08-18.
  it.each([
    "Часткове зняття банки «просто»",
    "  часткове зняття банки «Подушка»",
    "Поповнення «просто»",
    'Поповнення "накопичення"',
    "Поповнення „резерв“",
    "Переказ на свою картку",
    "Переказ зі своєї картки",
  ])("переказ: %s", (d) => {
    expect(isLikelyOwnTransfer(d)).toBe(true);
  });

  it.each([
    // Донат у чужу банку — « від » після назви (латинська i як у реальному
    // mono-експорті).
    "Поповнення «На допомогу Єнчику» вiд Віктор К.",
    "Поповнення «збір» від Марія П.",
    // Поповнення без лапок — не банка.
    "Поповнення картки",
    "Поповнення рахунку +380000000000",
    // Звичайні операції.
    "АТБ-Маркет",
    "Netflix",
    "Переказ на картку 5375***1234",
    "",
    "   ",
  ])("НЕ переказ: %s", (d) => {
    expect(isLikelyOwnTransfer(d)).toBe(false);
  });
});
