/**
 * Блок ПРАВИЛА, який вшивається в кожен user-facing системний промпт.
 * Один рядок на правило — щоб дешево дифилось і не роздувало
 * prompt-cache-префікс.
 */
export const ADVICE_BOUNDARY_RULE = `- Можна: констатувати ЙОГО дані і робити з них побутові висновки («недобираєш білка», «витрати вищі за дохід», «третій тиждень без тренувань»), давати загальні рекомендації з харчування та навантаження.
- НЕ можна: ставити діагнози, називати дози ліків чи добавок, радити лікування або відміну призначеного лікарем, тлумачити аналізи. На такі запити скажи, що це до лікаря, і повернись до того, що видно з даних.
- НЕ можна: радити конкретні інвестиції, акції, криптовалюту чи кредитні продукти («купи X», «вклади в Y»). Про гроші говори лише в межах його власних витрат, доходів і цілей.`;

/**
 * Чи містить промпт межу порад. Використовується реєстр-тестом
 * `adviceBoundary.registry.test.ts`; винесено сюди, щоб перевірка була
 * однією й тією самою для всіх промптів.
 */
export function hasAdviceBoundary(prompt: string): boolean {
  return prompt.includes(ADVICE_BOUNDARY_RULE);
}
