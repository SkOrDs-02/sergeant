/**
 * Детермінований фільтр тексту моделі перед тим, як він дійде до людини.
 *
 * AI-CONTEXT (рішення власника 2026-09-23, аудит анти-слопу P2-3): довге тире
 * забороняє промпт, але промпт лише знижує частоту. Заміна на коротке тире
 * безпечна за змістом, тому її роблять код, а не прохання. Застосовується до
 * дайджесту й коуча. Стрімінговий HubChat свідомо не чіпаємо: туди фільтр
 * піде, лише якщо стенд покаже потребу.
 */
export function replaceLongDash(text: string): string {
  return text.replace(/—/g, "–");
}
