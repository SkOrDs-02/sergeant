import { describe, expect, it } from "vitest";

import {
  PERSON_PLACEHOLDER,
  maskMachineText,
  maskUserText,
  normalizeKnownValues,
  redactKnownValues,
} from "./llmRedaction.js";

describe("normalizeKnownValues", () => {
  it("довші значення йдуть першими", () => {
    // Не косметика, а коректність: якщо спершу вирізати «Іван», то з
    // «Іван Петренко» лишиться «[особа] Петренко» — прізвище вціліє.
    expect(normalizeKnownValues(["Іван", "Іван Петренко"])).toEqual([
      "Іван Петренко",
      "Іван",
    ]);
  });

  it("викидає надто короткі значення", () => {
    // «Оля» як підрядок трапляється всередині звичайних слів; вирізати
    // трилітерні значення означає покришити половину описів.
    expect(normalizeKnownValues(["Оля", "Олена"])).toEqual(["Олена"]);
  });

  it("викидає значення без жодної літери", () => {
    // Чисті номери — робота класу А (`maskPii`), не наша.
    expect(normalizeKnownValues(["1234567890"])).toEqual([]);
  });

  it("дедуплікує без урахування регістру", () => {
    expect(normalizeKnownValues(["Петренко", "петренко"])).toEqual([
      "Петренко",
    ]);
  });

  it("нулі й undefined не ламають нормалізацію", () => {
    expect(normalizeKnownValues([null, undefined, "Петренко"])).toEqual([
      "Петренко",
    ]);
  });
});

describe("redactKnownValues", () => {
  it("вирізає імʼя контрагента з опису переказу", () => {
    expect(
      redactKnownValues("Від: Іван Петренко, дякую", ["Іван Петренко"]),
    ).toBe(`Від: ${PERSON_PLACEHOLDER}, дякую`);
  });

  it("не чіпає слово, всередині якого випадково лежить значення", () => {
    // Найдорожчий баг цього модуля: заміна підрядка без меж слова. Якби
    // межі не працювали, «Петренківська» стала б «[особа]ківська» — і
    // тихо, бо жоден тип не заперечить.
    expect(redactKnownValues("вулиця Петренківська", ["Петренко"])).toBe(
      "вулиця Петренківська",
    );
  });

  it("межі слова працюють на кирилиці, а не лише на латині", () => {
    // `\b` у JS рахує межею будь-який не-ASCII символ, тому наївний
    // `\bІван\b` спрацював би там, де не мав. Перевіряємо саме кирилицю.
    expect(redactKnownValues("Іванченко переказав", ["Іван"])).toBe(
      "Іванченко переказав",
    );
    expect(redactKnownValues("Іван переказав", ["Іван"])).toBe(
      `${PERSON_PLACEHOLDER} переказав`,
    );
  });

  it("регістр не рятує від вирізання", () => {
    expect(redactKnownValues("від ІВАН ПЕТРЕНКО", ["Іван Петренко"])).toBe(
      `від ${PERSON_PLACEHOLDER}`,
    );
  });

  it("порожній список значень лишає текст як є", () => {
    expect(redactKnownValues("Сільпо на Хрещатику", [])).toBe(
      "Сільпо на Хрещатику",
    );
  });

  it("спецсимволи у значенні не стають регекспом", () => {
    // Імʼя з дужкою зламало б `new RegExp` без екранування — і впав би
    // весь чат, а не одне маскування.
    expect(() => redactKnownValues("текст", ["ТОВ (Ромашка)"])).not.toThrow();
    expect(
      redactKnownValues("платіж ТОВ (Ромашка) ok", ["ТОВ (Ромашка)"]),
    ).toBe(`платіж ${PERSON_PLACEHOLDER} ok`);
  });
});

describe("maskUserText", () => {
  it("маскує ідентифікатори класу А", () => {
    const masked = maskUserText("пиши на ivan@mail.com або +380671234567");
    expect(masked).toContain("[email]");
    expect(masked).toContain("[phone]");
  });

  it("НЕ вирізає імена — це клас В, відкладений власником", () => {
    // Головний асерт файлу і навмисно зворотний до інтуїції «маскуй
    // більше». Текст користувача під клас Б не потрапляє: вирізане імʼя
    // без повернення у відповідь дало б «[особа] винна тобі 500».
    expect(maskUserText("скільки я винен Олені Петренко")).toBe(
      "скільки я винен Олені Петренко",
    );
  });
});

describe("maskMachineText", () => {
  it("застосовує обидва класи", () => {
    const masked = maskMachineText(
      "Від: Іван Петренко, ivan@mail.com, 500 грн",
      ["Іван Петренко"],
    );
    expect(masked).toBe(`Від: ${PERSON_PLACEHOLDER}, [email], 500 грн`);
  });

  it("суми, категорії й назви крамниць лишаються недоторканими", () => {
    // Пряма перевірка другої половини рішення #10. Якщо цей асерт колись
    // впаде — маскування зʼїло сенс порад, і це регресія, а не «стало
    // безпечніше».
    const text = "Сільпо, продукти, 342.50 грн, картка ***1234";
    expect(maskMachineText(text, ["Іван Петренко"])).toBe(text);
  });

  it("ідемпотентне — повторний прохід нічого не змінює", () => {
    // Маска стоїть у кількох місцях конвеєра; накладання не має
    // перетворювати «[особа]» на «[[особа]]».
    const once = maskMachineText("Від: Іван Петренко", ["Іван Петренко"]);
    expect(maskMachineText(once, ["Іван Петренко"])).toBe(once);
  });
});
