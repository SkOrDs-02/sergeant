#!/usr/bin/env node
// ---------------------------------------------------------------------------
// gen-design-md.mjs — regenerate the machine-owned palette tables in DESIGN.md
// straight from the design-token source of truth.
// ---------------------------------------------------------------------------
//
// WHY THIS EXISTS
//   DESIGN.md is the portable config AI agents read BEFORE styling. It used to
//   hand-mirror the palette, so it silently drifted from tokens.js — e.g. the
//   finyk row still said `emerald-500 #10b981` months after finyk migrated to
//   teal, and the nutrition macro-ring colours listed blue/yellow/green after
//   the code had already moved to cyan/coral/lime. Agents that "read DESIGN.md
//   first" were being handed a false palette, which seeds fresh violations.
//
//   This script owns the region between the AUTOGEN markers and rewrites it
//   from `packages/design-tokens/tokens.js`. Prose OUTSIDE the markers stays
//   hand-authored.
//
// USAGE
//   node scripts/gen-design-md.mjs            # rewrite DESIGN.md in place
//   node scripts/gen-design-md.mjs --check    # CI: exit 1 if out of date
//
import { readFileSync, writeFileSync } from "node:fs";
import prettier from "prettier";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const tokensPath = resolve(repoRoot, "packages/design-tokens/tokens.js");
const designMdPath = resolve(repoRoot, "DESIGN.md");

const tokens = require(tokensPath);
const { moduleColors, moduleAccentRgb, statusHex, chartHex, inkTheme } = tokens;

const BEGIN =
  "<!-- AUTOGEN:palette — generated by scripts/gen-design-md.mjs. Do not edit by hand. -->";
const END = "<!-- /AUTOGEN:palette -->";

// `moduleAccentRgb.<m>.strong` is an "R G B" triple; DESIGN.md shows hex.
function rgbTripleToHex(triple) {
  const [r, g, b] = triple.trim().split(/\s+/).map(Number);
  const h = (n) => n.toString(16).padStart(2, "0");
  return `#${h(r)}${h(g)}${h(b)}`;
}

// Human-facing Tailwind family label per module, kept beside the hex so the
// table still reads like the old hand-written one. This is the ONE piece of
// naming that lives here rather than in tokens (tokens store hex, not family
// names); if a module migrates hue, update this map in the same commit.
const MODULE_FAMILY = {
  finyk: { primary: "teal-700", strong: "teal-800" },
  fizruk: { primary: "cyan-700", strong: "cyan-800" },
  routine: { primary: "coral-500", strong: "coral-700" },
  nutrition: { primary: "lime-500", strong: "lime-800" },
};

const MACRO_LABEL = {
  protein: "protein",
  fat: "fat",
  carbs: "carbs",
};

function buildBlock() {
  const rows = Object.keys(MODULE_FAMILY).map((m) => {
    const c = moduleColors[m];
    const fam = MODULE_FAMILY[m];
    const primary = `${fam.primary} \`${c.primary}\``;
    const strongHex = rgbTripleToHex(moduleAccentRgb[m].strong);
    const strong = `${fam.strong} \`${strongHex}\``;
    return `| ${m.padEnd(9)} | ${primary.padEnd(21)} | ${strong.padEnd(31)} | \`${c.surface}\` |`;
  });

  const statusLine = Object.entries(statusHex)
    .map(([k, v]) => `${k} \`${v}\``)
    .join(" · ");

  const macroLine = Object.keys(MACRO_LABEL)
    .map((k) => `${MACRO_LABEL[k]} \`${chartHex[k]}\``)
    .join(", ");

  const inkAccent = Object.entries(inkTheme.accent)
    .map(([k, v]) => `${k} \`${v}\``)
    .join(" · ");

  return [
    BEGIN,
    "",
    "**Акцент = модуль** (module-accent containment, дизайн-конвенція — чужий акцент у чужому модулі заборонений):",
    "",
    "| Модуль    | primary               | strong (WCAG-AA під text-white) | surface   |",
    "| --------- | --------------------- | ------------------------------- | --------- |",
    ...rows,
    "",
    "Правило `-strong`: насичений brand-fill під `text-white` → тільки `-strong` companion (дизайн-конвенція). У коді — через `--module-accent-rgb` / `--module-accent-strong-rgb` (ModuleAccentProvider), не хардкод hex.",
    "",
    `**Статуси:** ${statusLine}. Семантичний колір ≠ акцент модуля.`,
    "",
    `**Charts:** 8-колірна органічна палітра (\`chartPalette\` у tokens.js); макро-кільця nutrition: ${macroLine} (kcal бере статус-hue).`,
    "",
    `**Ink-акценти (dark):** ${inkAccent} — tier-400 модуля; текст поверх акцент-філу завжди ink, ніколи білий.`,
    "",
    END,
  ].join("\n");
}

// AI-CONTEXT: вихід генератора ОБОВʼЯЗКОВО проганяється через Prettier — так
// само, як у `scripts/docs/generate-hard-rules-matrix.mjs`. Без цього два
// гейти суперечать один одному: `design:check-md` порівнює блок палітри
// дослівно, а `format:check` перевирівнює markdown-таблицю, і полагодити
// обидва одночасно стає неможливо (кожен фікс ламає інший).
async function formatMarkdown(content) {
  const opts = (await prettier.resolveConfig(designMdPath)) ?? {};
  return prettier.format(content, { ...opts, parser: "markdown" });
}

async function main() {
  const check = process.argv.includes("--check");
  const md = readFileSync(designMdPath, "utf8");

  const beginIdx = md.indexOf(BEGIN);
  const endIdx = md.indexOf(END);
  if (beginIdx === -1 || endIdx === -1) {
    console.error(
      `[gen-design-md] AUTOGEN markers not found in DESIGN.md.\n` +
        `Add the following two lines around the palette block:\n  ${BEGIN}\n  ${END}`,
    );
    process.exit(2);
  }

  const before = md.slice(0, beginIdx);
  const after = md.slice(endIdx + END.length);
  const next = await formatMarkdown(`${before}${buildBlock()}${after}`);

  if (next === md) {
    if (check) console.log("[gen-design-md] DESIGN.md palette is up to date.");
    return;
  }

  if (check) {
    console.error(
      "[gen-design-md] DESIGN.md palette is OUT OF DATE with tokens.js.\n" +
        "Run `node scripts/gen-design-md.mjs` and commit the result.",
    );
    process.exit(1);
  }

  writeFileSync(designMdPath, next, "utf8");
  console.log("[gen-design-md] DESIGN.md palette regenerated from tokens.js.");
}

await main();
