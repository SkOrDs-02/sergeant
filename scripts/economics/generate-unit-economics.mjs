#!/usr/bin/env node
// ---------------------------------------------------------------------------
// generate-unit-economics.mjs — перерахунок числових таблиць у
// docs/01-product/launch/business/07-unit-economics.md з `assumptions.json`.
// ---------------------------------------------------------------------------
//
// Проза поза маркерами AUTOGEN — рукописна. Усе між ними належить скрипту:
// змінив припущення → `pnpm economics` → таблиці і висновки перерахувались.
//
// USAGE
//   node scripts/economics/generate-unit-economics.mjs           # переписати док
//   node scripts/economics/generate-unit-economics.mjs --check   # CI: 1 якщо застаріло
//   node scripts/economics/generate-unit-economics.mjs --stdout  # надрукувати блок
//
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import {
  anonAiCostUsd,
  breakEven,
  breakEvenConversion,
  contributionMargin,
  fixedCosts,
  freeAiCostUsd,
  loadAssumptions,
  ltv,
  proAiCostUsd,
  revenue,
  trialCost,
  unitsPerMessage,
} from "./model.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "../..");
const docPath = resolve(
  repoRoot,
  "docs/01-product/launch/business/07-unit-economics.md",
);

const BEGIN =
  "<!-- AUTOGEN:economics — generated by scripts/economics/generate-unit-economics.mjs. Do not edit by hand. -->";
const END = "<!-- /AUTOGEN:economics -->";

// Мінус ставимо ПЕРЕД знаком валюти («−₴89»), а не всередині («₴-89») —
// інакше таблиця читається як ціна з дефісом.
const uah = (n) =>
  `${n < 0 ? "−" : ""}₴${Math.abs(n).toFixed(Math.abs(n) >= 100 ? 0 : 2)}`;
const usd = (n) => `$${n.toFixed(n >= 1 ? 2 : 4)}`;
const pct = (n) => `${n.toFixed(1)}%`;
const num = (n) => (Number.isFinite(n) ? n.toFixed(1) : "∞");

function table(header, rows) {
  const sep = header.map(() => "---");
  return [header, sep, ...rows].map((r) => `| ${r.join(" | ")} |`).join("\n");
}

function buildBlock(a) {
  const rev = revenue(a);
  const free = freeAiCostUsd(a);
  const anon = anonAiCostUsd(a);
  const trial = trialCost(a);
  const perMsg = unitsPerMessage(a);
  const profiles = Object.keys(a.usage.profiles).map((name) => ({
    name,
    ...proAiCostUsd(a, name),
    meta: a.usage.profiles[name],
  }));

  const out = [];
  const push = (...lines) => out.push(...lines, "");

  push(
    `_Перераховано з \`scripts/economics/assumptions.json\` (ціни перевірено ${a.meta.pricesCheckedOn}), курс ₴${a.fx.uahPerUsd.value}/$._`,
  );

  // 1. Виручка
  push(
    "### Що приносить один платник",
    "",
    table(
      ["Рядок", "₴/міс", "Коментар"],
      [
        ["Місячний план", uah(rev.monthlyUah), "ADR-0068"],
        [
          "Річний план у перерахунку на місяць",
          uah(rev.annualMonthlyUah),
          `₴${a.pricing.proAnnualUah.value}/рік`,
        ],
        [
          "**Blended ARPU**",
          `**${uah(rev.blendedArpuUah)}**`,
          `${pct(a.pricing.annualShare.value * 100)} на річному плані (припущення)`,
        ],
        [
          "− єдиний податок + військовий збір",
          `−${uah(rev.taxUah)}`,
          `${pct(rev.taxRate * 100)} від обороту`,
        ],
        [
          "− еквайринг",
          `−${uah(rev.acquiringUah)}`,
          `${pct(rev.acquiringRate * 100)} (plata by mono)`,
        ],
        ["**Чиста виручка до COGS**", `**${uah(rev.netRevenueUah)}**`, ""],
      ],
    ),
  );

  // 2. AI-COGS
  push(
    "### AI-COGS: скільки коштує обслуговувати одного користувача",
    "",
    `Одне повідомлення = два виклики (перший тур із інструментами + синтез). Одне повідомлення списує ${perMsg.toFixed(2)} одиниці квоти при частці інструментальних викликів ${pct(a.quota.toolShare.value * 100)}.`,
    "",
    table(
      [
        "Профіль Pro",
        "Повідомлень/добу",
        "Чат",
        "Коуч",
        "Фото",
        "Інше",
        "**Разом $/міс**",
        "**₴/міс**",
      ],
      profiles.map((p) => [
        `**${p.name}** — ${p.meta.note}`,
        String(p.meta.chatMsgsPerDay),
        usd(p.chatUsd),
        usd(p.coachUsd),
        usd(p.visionUsd),
        usd(p.digestUsd + p.miscUsd),
        `**${usd(p.usd)}**`,
        `**${uah(p.uah)}**`,
      ]),
    ),
    "",
    table(
      ["Неплатний трафік", "Що дозволяє код", "$/міс", "₴/міс"],
      [
        [
          "Free-користувач",
          `${a.quota.freeUnitsPerDay.value} одиниць/добу на чат + пораду коуча`,
          usd(free.usd),
          uah(free.uah),
        ],
        [
          "Анонім (на IP)",
          `${a.quota.anonUnitsPerDay.value} одиниця/добу`,
          usd(anon.usd),
          uah(anon.uah),
        ],
        [
          `Reverse trial (${a.funnel.trialDays.value} днів Pro)`,
          "квоти немає взагалі",
          usd(trial.perSignupUah / a.fx.uahPerUsd.value),
          uah(trial.perSignupUah),
        ],
      ],
    ),
  );

  // 3. Фіксовані
  const phases = Object.keys(a.phases).map((p) => fixedCosts(a, p));
  push(
    "### Фіксовані витрати за фазами",
    "",
    table(
      ["Рядок", ...phases.map((p) => p.label)],
      [
        ...phases[0].lines.map((_, i) => [
          phases[0].lines[i].label,
          ...phases.map((p) => (p.lines[i].uah ? uah(p.lines[i].uah) : "—")),
        ]),
        ["**Разом**", ...phases.map((p) => `**${uah(p.totalUah)}**`)],
      ],
    ),
    "",
    `Частка ЄСВ у фіксованих витратах фази «${phases[1].label}» — ${pct((a.taxes.esvMonthlyUah.value / phases[1].totalUah) * 100)}. Це найбільший рядок постійних витрат, більший за весь хостинг разом.`,
  );

  // 4. Маржа і breakeven
  const cmOwn = contributionMargin(a, { includeFreeCohort: false });
  const cmFull = contributionMargin(a, { includeFreeCohort: true });
  const beOwn = breakEven(a, { includeFreeCohort: false, phase: "launch" });
  const beFull = breakEven(a, { includeFreeCohort: true, phase: "launch" });
  const beConv = breakEvenConversion(a);

  push(
    "### Внесок платника і точка беззбитковості",
    "",
    table(
      ["Рядок", "Без Free-когорти", "З Free-когортою"],
      [
        ["Blended ARPU", uah(cmOwn.blendedArpuUah), uah(cmFull.blendedArpuUah)],
        [
          "− податки + еквайринг",
          `−${uah(cmOwn.taxUah + cmOwn.acquiringUah)}`,
          `−${uah(cmFull.taxUah + cmFull.acquiringUah)}`,
        ],
        [
          "− власний AI платника",
          `−${uah(cmOwn.proAiUah)}`,
          `−${uah(cmFull.proAiUah)}`,
        ],
        [
          "− Free-користувачі на одного платника",
          "—",
          `−${uah(cmFull.freeCohortUah)} (${num(cmFull.activeFreePerPaid)} активних Free)`,
        ],
        [
          "**Внесок (contribution margin)**",
          `**${uah(cmOwn.marginUah)}**`,
          `**${uah(cmFull.marginUah)}**`,
        ],
        ["Маржа від ARPU", pct(cmOwn.marginPct), pct(cmFull.marginPct)],
        [
          `**Беззбитковість, платників (фаза «${beOwn.phase}»)**`,
          `**${num(beOwn.subscribers)}**`,
          `**${num(beFull.subscribers)}**`,
        ],
      ],
    ),
    "",
    `**Критична конверсія — ${pct(beConv * 100)}.** Нижче неї безкоштовний трафік з'їдає весь внесок платника, і беззбитковості не існує за жодної кількості підписників. Поточне робоче припущення — ${pct(a.funnel.conversionFreeToPaid.value * 100)}, медіана freemium B2C — 3.7%.`,
  );

  // 5. LTV / CAC
  const l = ltv(a, { includeFreeCohort: true });
  const lOwn = ltv(a, { includeFreeCohort: false });
  push(
    "### LTV, CAC, окупність",
    "",
    table(
      ["Метрика", "З Free-когортою", "Без Free-когорти", "Як порахована"],
      [
        [
          "Тривалість життя підписки",
          `${num(l.lifetimeMonths)} міс`,
          `${num(lOwn.lifetimeMonths)} міс`,
          `1 / churn ${pct(a.funnel.monthlyChurn.value * 100)}`,
        ],
        [
          "LTV (на внеску, не на виручці)",
          uah(l.ltvUah),
          uah(lOwn.ltvUah),
          "внесок × тривалість життя",
        ],
        [
          "CAC — реклама",
          uah(l.cacAdsUah),
          uah(lOwn.cacAdsUah),
          "blended organic/paid",
        ],
        [
          "CAC — вартість reverse trial",
          uah(l.cacTrialUah),
          uah(lOwn.cacTrialUah),
          `${num(trial.signupsPerPaid)} signup-ів × ${uah(trial.perSignupUah)} на кожного платника`,
        ],
        [
          "**CAC разом**",
          `**${uah(l.cacUah)}**`,
          `**${uah(lOwn.cacUah)}**`,
          "",
        ],
        [
          "LTV:CAC",
          `${num(l.ratio)}:1`,
          `${num(lOwn.ratio)}:1`,
          "здорово > 3:1",
        ],
        [
          "Окупність",
          `${num(l.paybackMonths)} міс`,
          `${num(lOwn.paybackMonths)} міс`,
          "CAC / внесок",
        ],
      ],
    ),
    "",
    "Колонка «без Free-когорти» — це та економіка, яку описували попередні версії доків: вона рахує лише витрати самого платника. Різниця між колонками і є ціна безкоштовного тіру.",
  );

  // 6. Чутливість
  const sens = [];
  const clone = () => JSON.parse(JSON.stringify(a));
  const scenario = (label, mutate) => {
    const b = clone();
    mutate(b);
    const be = breakEven(b, { includeFreeCohort: true, phase: "launch" });
    sens.push([
      label,
      uah(be.marginUah),
      num(be.subscribers),
      `${be.marginUah - beFull.marginUah >= 0 ? "+" : "−"}₴${Math.abs(be.marginUah - beFull.marginUah).toFixed(0)}`,
    ]);
  };

  scenario("базовий сценарій", () => {});
  scenario(
    "конверсія 2% замість 4%",
    (b) => (b.funnel.conversionFreeToPaid.value = 0.02),
  );
  scenario("конверсія 8%", (b) => (b.funnel.conversionFreeToPaid.value = 0.08));
  scenario(
    "активних Free 80% замість 40%",
    (b) => (b.usage.activeFreeShare.value = 0.8),
  );
  scenario("активних Free 20%", (b) => (b.usage.activeFreeShare.value = 0.2));
  scenario("денна порада коуча для Free — на floor-моделі", (b) => {
    b.ai.coachUsd.value =
      b.ai.chatSynthesisFloorUsd.value + b.ai.chatFirstTurnUsd.value;
  });
  scenario("порада коуча для Free — 2 рази на тиждень замість щодня", (b) => {
    b.usage.freeProfile.coachPerDay = 2 / 7;
  });
  scenario(
    "Free-квота 3 одиниці/добу замість 5",
    (b) => (b.quota.freeUnitsPerDay.value = 3),
  );
  scenario(
    "усі платники на річному плані",
    (b) => (b.pricing.annualShare.value = 1),
  );
  scenario(
    "усі платники на місячному плані",
    (b) => (b.pricing.annualShare.value = 0),
  );
  scenario("еквайринг LiqPay 2.75% замість 1.3%", (b) => {
    b.acquiring.primaryRate.value = b.acquiring.fallbackRate.value;
  });
  scenario("кожен платник споживає як «medium» × 3", (b) => {
    b.usage.profiles.medium.chatMsgsPerDay *= 3;
  });
  scenario("ціна ₴249 замість ₴199 (річний +25%)", (b) => {
    b.pricing.proMonthlyUah.value = 249;
    b.pricing.proAnnualUah.value = 1862;
  });

  push(
    "### Чутливість: що справді рухає економіку",
    "",
    "Кожен рядок — зміна ОДНОГО припущення від базового сценарію; решта лишається на місці.",
    "",
    table(
      [
        "Зміна одного припущення",
        "Внесок/платника",
        "Беззбитковість, платників",
        "Δ внеску",
      ],
      sens,
    ),
  );

  // 7. Реєстр довіри до чисел
  const rows = [];
  const walk = (node, path) => {
    if (!node || typeof node !== "object") return;
    if (node.confidence) {
      rows.push([
        `\`${path}\``,
        String(node.value),
        node.confidence,
        node.source ?? "—",
      ]);
      return;
    }
    for (const [k, child] of Object.entries(node)) walk(child, `${path}.${k}`);
  };
  for (const [k, child] of Object.entries(a)) {
    if (k === "meta" || k === "phases") continue;
    walk(child, k);
  }
  const counts = rows.reduce(
    (acc, r) => ((acc[r[2]] = (acc[r[2]] ?? 0) + 1), acc),
    {},
  );

  push(
    "### Реєстр вхідних чисел",
    "",
    `Із ${rows.length} параметрів моделі: ${Object.entries(counts)
      .map(([k, n]) => `**${n}** ${k}`)
      .join(
        ", ",
      )}. Кожен \`estimated\` — це відкрите питання зі списку § «Чого ми не знаємо».`,
    "",
    table(["Параметр", "Значення", "Довіра", "Джерело"], rows),
  );

  return out.join("\n").trimEnd();
}

async function main() {
  const a = loadAssumptions();
  const block = buildBlock(a);

  if (process.argv.includes("--stdout")) {
    process.stdout.write(`${block}\n`);
    return;
  }

  const doc = readFileSync(docPath, "utf8");
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1) {
    console.error(`✖ Маркери AUTOGEN не знайдено у ${docPath}`);
    process.exit(1);
  }

  const next = `${doc.slice(0, start + BEGIN.length)}\n\n${block}\n\n${doc.slice(end)}`;
  // Prettier — лише на шляху запису: `--stdout` має працювати без
  // встановлених залежностей (наприклад, у свіжому клоні до `pnpm install`).
  const { default: prettier } = await import("prettier");
  const formatted = await prettier.format(next, { parser: "markdown" });

  if (process.argv.includes("--check")) {
    if (formatted !== doc) {
      console.error(
        "✖ 07-unit-economics.md застарів щодо assumptions.json — запусти `pnpm economics`",
      );
      process.exit(1);
    }
    console.log("✓ 07-unit-economics.md актуальний");
    return;
  }

  writeFileSync(docPath, formatted);
  console.log(`✓ Оновлено ${docPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
